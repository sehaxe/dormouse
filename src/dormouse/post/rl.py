@dataclass(frozen=True)
class RLConfig:
    """The reward/advantage knobs in one dataclass.

    The notes' placeholders (X/B/A/δ/s/γ, with their sourced ranges in the
    comments) are fields here; the defaults are the SHIPPED ones, and the length
    penalty's default is OFF because the notes' §3.1 "ARGUMENTS TO FILL" says
    nobody has measured them at our scale yet.
    """

    #: `S_sol`'s proxy: "thrift" (bytes vs the reference) or "none" (`S_sol = 1`).
    quality: str = "thrift"
    #: X — the penalty's ceiling, 0.2-0.5 when measured; 0.0 disables the term.
    length_penalty: float = 0.0
    #: B — the percentile of the SUCCESSFUL lengths that sets `ℓ*_q`, 0.5-0.75.
    quantile: float = 0.5
    #: A — the group pass rate the term needs, 0.3-0.5.
    gate: float = 0.4
    #: δ — the free band above `ℓ*_q`, 0.0-0.1.
    delta: float = 0.0
    #: s — where the penalty saturates, as a multiple of `ℓ*_q`; s > δ.
    s: float = 0.5
    #: γ — the ramp's exponent, 1-2.
    gamma: float = 1.0
    #: The loss normaliser: "prompt-mean" (this lane's rule) or "token-mean" (the
    #: control arm the notes' §4.2 A/B names).
    agg: str = "prompt-mean"

    def __post_init__(self) -> None:
        if self.quality not in ("thrift", "none"):
            loud(
                f"RLConfig quality={self.quality!r}: known proxies are 'thrift' (bytes "
                f"against the hidden reference) and 'none' (S_sol = 1). Escape: a "
                f"learned/LLM judge is a later, measured node (notes §3.1)."
            )
        if self.agg not in ("prompt-mean", "token-mean"):
            loud(
                f"RLConfig agg={self.agg!r}: known aggregations are 'prompt-mean' (this "
                f"lane's rule) and 'token-mean' (the A/B control). Escape: one of those."
            )
        if self.length_penalty < 0.0:
            loud(
                f"RLConfig length_penalty={self.length_penalty}: X is a penalty, so it "
                f"cannot be negative (0.0 disables the term). Escape: X >= 0."
            )
        if not 0.0 < self.quantile < 1.0:
            loud(
                f"RLConfig quantile={self.quantile}: B is a percentile of the successful "
                f"lengths, strictly inside (0, 1) (0.5-0.75 is the sourced band)."
            )
        if not 0.0 <= self.gate <= 1.0:
            loud(f"RLConfig gate={self.gate}: A is a pass rate, so it lies in [0, 1].")
        if self.delta < 0.0:
            loud(f"RLConfig delta={self.delta}: δ is a free band above ℓ*_q, so δ >= 0.")
        if self.s <= self.delta:
            loud(
                f"RLConfig s={self.s} <= delta={self.delta}: Eq. 4's ramp "
                f"clip((len/ℓ*_q − 1 − δ)/(s − δ), 0, 1) divides by zero. Escape: s > δ."
            )
        if self.gamma <= 0.0:
            loud(f"RLConfig gamma={self.gamma}: γ is the ramp's exponent, so γ > 0.")


@dataclass(frozen=True)
class GroupStats:
    """One prompt group's length statistics — what makes the penalty group-relative."""

    n: int
    pass_rate: float
    #: ℓ*_q — the B-th percentile of the SUCCESSFUL lengths (0.0 when none passed).
    quantile_len: float
    #: True when a quantile exists AND the group's pass rate cleared `cfg.gate`.
    gate_open: bool


@dataclass(frozen=True)
class RewardTerms:
    """One item's reward, every term named so a log line can carry all of them."""

    r_test: float
    s_sol: float
    s_beh: float
    length_penalty: float
    total: float
    #: True when the length term was EVALUATED for this item (gate open + it passed).
    len_penalty_active: bool


@dataclass(frozen=True)
class Sample:
    """One rollout as the policy-gradient step reads it.

    `prompt` and `response` are the bytes the forward consumes; `rollout` is the
    existing [`Rollout`] the advantage arms read (the CRR arm needs its trace and
    its verdict). Build one with [`Sample.from_rollout`] rather than by hand: the
    response's bytes live in the trace's hex records, and re-deriving them is
    exactly the kind of second implementation that drifts.
    """

    prompt: bytes
    response: bytes
    group: int
    rollout: Rollout | None = None

    @classmethod
    def from_rollout(cls, task: Task, rollout: Rollout, group: int) -> Sample:
        """The ONE bridge from the rollout runner's output to a trainable sample."""
        return cls(
            prompt=task.prompt.encode("utf-8"),
            response=bytes(int(stroke, 16) for stroke in rollout.trace),
            group=group,
            rollout=rollout,
        )


@dataclass(frozen=True)
class RLAdvantage:
    """One sample's advantage, aligned with the sample list by `index`."""

    index: int
    value: float
    group: int
    #: "pass" | "fork_history" | "empty" (CRR) | "group" | "consensus" (group mode).
    source: str


