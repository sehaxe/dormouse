"""The RL stepper: MiMo-style rewards, CRR/group advantages, one policy-gradient step.

Sources: `docs/research/2026-10-15-mimo-rl-notes.md` §3.1 (the reward node) and
`docs/architecture/post-training.md`'s "Reward shape for token thrift" node —
MiMo-V2.6 (2610.11959) Eq. 2, `R = R_test · S_sol · S_beh`, **multiplicative**, so
a zero in ANY factor cannot be bought back by the others; plus Eq. 4's
group-relative length penalty, gated on the group's pass rate, with prompt-mean
loss aggregation.

**Reused, not re-implemented.** The `"crr"` advantage arm delegates to
`post.train_steps.crr_advantage` (2609.33875's fork-replay shape, already in this
lane) — its pass/fail signal comes from the rollout, so the arm reads the group's
`Rollout`s, not the shaped reward's magnitude. The sampler is
`post.rollouts.rollout`; [`Sample.from_rollout`] is the ONE bridge from a
`Rollout` to the bytes a policy-gradient forward reads (a trace entry is the
2-char hex record of one generated byte, `rollouts.py:86`). `Counters` and `loud`
are the instrument layer's marks (ADR-0011).

**The reward, and what it is not.** `R_test` is the verifier's own verdict — the
deterministic grader this lane is built on. `S_sol` is the **thrift proxy**
(`--quality heuristic`, the notes' default): a response that costs no more bytes
than the hidden reference is full quality, a response twice as long is half. No
LLM judge is called anywhere (notes §3.1: at 57M active the judge would be the
network under training — the sourced failure mode). `S_beh` flags the two
degenerate behaviours a `Verdict` can show: an empty response, and a verifier
refusal (`verifiers.py:211`, the anti-reward-hack screen). MiMo's token-level
behaviour penalty (Eq. 5) is **deferred** — the notes' transfer table says
"later", it needs per-token flags — but the field is here so it can land without
a signature change.

**The length penalty is a separate, group-relative term.** `ℓ*_q` is the B-th
percentile of the SUCCESSFUL lengths in the prompt's group, the gate is the
group's pass rate > A, and below the gate the term is **inactive and COUNTED**
(`rl_len_penalty_gated`) — a no-op that cannot look like a mechanism. The X/B/A/
δ/s/γ arguments are placeholders the notes leave to us; the shipped default is
`length_penalty = 0.0`, i.e. OFF, because nobody has measured them at this scale.

**Named deviations** (ADR-0011): no `--grade add|none` (the multiplicative shape
is the one this lane ships), no importance-sampling clip and no staleness (this
loop is synchronous and single-process — §1.5 forbids two GPU processes), no
value head (MiMo's GRPO has none either; the fork-replay arm is the alternative).
And one **COUNTED** degradation: a capacity-dropping MoE (`moe_topk > 0` at
`moe_capacity > 0`) is not prefix-causal, so a teacher-forced full-window forward
is not the growing-window forward that sampled the bytes (`decode.py:46-49`'s
rule) — `rl_non_causal_logp` counts it. `moe_topk = 0` is immune.
"""

