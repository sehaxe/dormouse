def rl_advantages(
    rewards: Sequence[float],
    group_ids: Sequence[int],
    mode: str,
    *,
    samples: Sequence[Sample] | None = None,
) -> list[RLAdvantage]:
    """Per-sample advantages, index-aligned with the batch. Two arms:

    - `"group"` — GRPO's `(r − group_mean) / group_std` over the prompt's own
      group (population std, i.e. the group is the population). A group with zero
      spread — every sample passed, or every sample failed — carries no signal at
      all, so its advantages are exactly 0 and the source says `"consensus"`;
      the notes' dynamic sampler drops such groups, and `rl_step` counts them.
    - `"crr"` — delegates to `post.train_steps.crr_advantage`, one call per group,
      and re-indexes its `Advantage` list back into the batch. It reads the
      group's ROLLOUTS (`samples`, required here), not the shaped reward: the
      fork-replay shape is defined on the pass/fail verdict (`train_steps.py:39`).

    Both arms aggregate per PROMPT: the group is the unit, so no prompt's length
    can buy it weight — the normaliser that turns that into a loss is
    [`sample_weights`], applied in [`rl_step`].
    """
    if len(rewards) != len(group_ids):
        loud(
            f"rl_advantages: {len(rewards)} rewards vs {len(group_ids)} group ids. "
            f"Escape: one group id per reward."
        )
    if mode not in ("crr", "group"):
        loud(f"rl_advantages mode={mode!r}: known arms are 'crr' and 'group'.")
    if mode == "crr" and samples is None:
        loud(
            "rl_advantages mode='crr': the fork-replay advantage is read off each "
            "group's Rollout (its trace's depth and its verdict), so the samples are "
            "required. Escape: pass samples=[Sample.from_rollout(...)], or mode='group'."
        )
    if samples is not None and len(samples) != len(rewards):
        loud(
            f"rl_advantages: {len(samples)} samples vs {len(rewards)} rewards — the "
            f"CRR arm re-indexes the group's advantages into the batch, so the two "
            f"lists must be the same batch. Escape: one sample per reward."
        )
    groups = list(dict.fromkeys(group_ids))  # first-appearance order, deterministic
    out: list[RLAdvantage] = []
    for g in groups:
        idx = [i for i, gi in enumerate(group_ids) if gi == g]
        values = [float(rewards[i]) for i in idx]
        if mode == "group":
            mean = sum(values) / len(values)
            var = sum((v - mean) ** 2 for v in values) / len(values)
            std = math.sqrt(var)
            source = "group" if std > 0.0 else "consensus"
            for i, v in zip(idx, values, strict=True):
                out.append(RLAdvantage(i, 0.0 if std == 0.0 else (v - mean) / std, g, source))
        else:
            assert samples is not None  # the loud check above
            group_rollouts: list[Rollout] = []
            for i in idx:
                r = samples[i].rollout
                if r is None:
                    loud(
                        f"rl_advantages mode='crr': samples[{i}] carries no Rollout "
                        f"(rollout=None), so the fork-replay advantage cannot read its "
                        f"depth or its verdict. Escape: Sample.from_rollout(...)."
                    )
                group_rollouts.append(r)
            for i, a in zip(idx, crr_advantage(group_rollouts), strict=True):
                out.append(RLAdvantage(i, a.value, g, a.source))
    return sorted(out, key=lambda a: a.index)


