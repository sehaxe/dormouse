def sample_weights(lengths: Sequence[int], groups: Sequence[int], cfg: RLConfig) -> list[float]:
    """`w_i` — the aggregation normaliser, one number per sample.

    `"prompt-mean"`: `1/G` for every sample of the group, so a terse correct
    answer weighs as much as a verbose one (MiMo's rule, and the notes' §4.2
    control is `token-mean`). `"token-mean"`: `len_i / Σ_group len`. An all-empty
    group has no token mass and falls back to `1/G` — its samples are skipped by
    `rl_step` either way, so the fallback prices nothing.
    """
    if len(lengths) != len(groups):
        loud(
            f"sample_weights: {len(lengths)} lengths vs {len(groups)} groups. Escape: "
            f"one group per sample."
        )
    by_group: dict[int, list[int]] = {}
    for i, g in enumerate(groups):
        by_group.setdefault(g, []).append(i)
    weights = [0.0] * len(groups)
    for idx in by_group.values():
        total = sum(lengths[i] for i in idx)
        for i in idx:
            if cfg.agg == "prompt-mean" or total == 0:
                weights[i] = 1.0 / len(idx)
            else:
                weights[i] = lengths[i] / total
    return weights


def pg_loss(
    logp_sums: torch.Tensor,
    weights: Sequence[float],
    advantages: Sequence[float],
    groups: Sequence[int],
) -> torch.Tensor:
    """`−(1/N_prompts) · Σ_i w_i · A_i · Σ_j logp_ij`, the advantage DETACHED.

    `logp_sums` is `[n]` (one Σ log-prob per sample), `weights` is
    [`sample_weights`], `groups` names each sample's prompt. The advantage enters
    as a constant tensor: it is a reward, not a differentiable function of the
    parameters, and building the coefficient this way is the `detach()` the
    formula calls for — no `.detach()` on a live graph that could be forgotten.

    `N_prompts` counts the prompts that CONTRIBUTED a sample: a group whose every
    advantage is zero is the notes' dropped all-pass/all-fail group, and it does
    not dilute the batch's gradient.
    """
    n = logp_sums.numel()
    if not (len(weights) == len(advantages) == len(groups) == n):
        loud(
            f"pg_loss: {n} log-prob sums, {len(weights)} weights, {len(advantages)} "
            f"advantages, {len(groups)} groups. Escape: one of each per sample."
        )
    n_prompts = len(set(groups))
    coef = torch.tensor(
        [w * a for w, a in zip(weights, advantages, strict=True)],
        dtype=torch.float32,
        device=logp_sums.device,
    )
    return -(coef * logp_sums).sum() / n_prompts


def response_logp(
    logits: torch.Tensor, ids: torch.Tensor, prompt_lens: int | Sequence[int]
) -> torch.Tensor:
    """Σ_j log π(ids[j] | ids[:j]) over the RESPONSE positions, one sum per row.

    `logits` is `[b*t, vocab]` (the model's own shape) and `ids` the `[b, t]` byte
    window the forward consumed. **The index that matters:** position `j−1` is
    what predicts byte `j`, so `logp[j]` is `log_softmax(logits[j−1])[ids[j]]` —
    never `logits[j]`. The first `prompt_len` bytes are the context, not the
    model's output, and are never scored.
    """
    assert ids.ndim == 2, f"ids must be [b, t], got {tuple(ids.shape)}"
    b, t = ids.shape
    assert t >= 2, f"a {t}-byte window has no next-byte position to score"
    assert logits.shape[0] == b * t, "logits rows != window positions"
    lens = [prompt_lens] * b if isinstance(prompt_lens, int) else list(prompt_lens)
    assert len(lens) == b, f"{len(lens)} prompt lengths for {b} rows"
    if any(not 1 <= p <= t for p in lens):
        loud(
            f"response_logp: prompt_lens={lens} must lie in [1, {t}]: a row with no "
            f"prompt has no context, and a prompt past the window is a caller bug. "
            f"Escape: prompt + response must fit the model's window."
        )
    pl = torch.as_tensor(lens, dtype=torch.long, device=ids.device)
    lp = torch.log_softmax(logits.reshape(b, t, -1).float(), dim=-1)
    picked = lp[:, :-1, :].gather(-1, ids[:, 1:].unsqueeze(-1)).squeeze(-1)  # [b, t-1]
    pos = torch.arange(1, t, device=ids.device).unsqueeze(0)
    return (picked * (pos >= pl.unsqueeze(1))).sum(dim=-1)


