def rl_step(
    model,
    opt,
    samples: Sequence[Sample],
    advantages: Sequence[RLAdvantage],
    cfg: RLConfig,
    *,
    counters: Counters | None = None,
) -> tuple[torch.Tensor, Counters]:
    """ONE policy-gradient step's forward and loss. Returns `(loss, counters)`.

    The forward is teacher-forced over `prompt + response` per sample with
    `targets=None` — the decode readout, the same logits generation sampled from
    and the eval line's `fin` scores — and the loss gathers the log-prob of the
    SAMPLED response bytes at their own positions ([`response_logp`]).

    **The caller owns `loss.backward()` and `opt.step()`** (this function zeroes
    the gradients, before the forward, so the step consumes the gradient it
    built). If `counters["rl_samples"] == 0` nothing contributed — every sample
    was skipped — and the returned loss is a grad-carrying zero: skip the
    backward AND the step (an AdamW step on zero gradients still applies weight
    decay).

    Samples are forwarded ONE at a time, not padded into one batch: a
    capacity-dropping MoE's drop set is a function of the whole window's
    composition, so a batch would change each sample's own logits (and the
    counter says so).
    """
    if len(samples) != len(advantages):
        loud(
            f"rl_step: {len(samples)} samples vs {len(advantages)} advantages — the "
            f"lists are index-aligned (rl_advantages sorts by index). Escape: one "
            f"advantage per sample."
        )
    if not samples:
        loud("rl_step: an empty batch has no policy gradient to take.")
    counters = Counters() if counters is None else counters
    opt.zero_grad(set_to_none=True)
    params = list(model.parameters())
    assert params, "rl_step needs a model with parameters (the device comes from them)"
    dev = params[0].device
    window = int(model.cfg.max_seq_len)
    loop = getattr(model, "loop", None)
    moe = getattr(loop, "moe", None)
    if moe is not None and moe.topk > 0 and moe.capacity > 0.0:
        # A capacity-dropping MoE is not prefix-causal: the drop set depends on the
        # window's composition, so this teacher-forced forward is not the
        # growing-window forward that sampled the bytes (`decode.py:46-49`).
        counters.count("rl_non_causal_logp")
    lengths = [len(s.response) for s in samples]
    groups = [s.group for s in samples]
    weights = sample_weights(lengths, groups, cfg)
    sums: list[torch.Tensor] = []
    values: list[float] = []
    kept_groups: list[int] = []
    kept_weights: list[float] = []
    for i, (s, a) in enumerate(zip(samples, advantages, strict=True)):
        if a.index != i:
            loud(
                f"rl_step: advantages[{i}].index={a.index} — the advantage list must be "
                f"sorted by index and aligned with the samples. Escape: rl_advantages(...)."
            )
        if a.value == 0.0:
            counters.count("rl_skipped_no_advantage")
            continue
        if not s.response:
            counters.count("rl_skipped_empty_response")
            continue
        ids = s.prompt + s.response
        if len(ids) > window:
            loud(
                f"rl_step: sample {i} is {len(ids)} B (prompt {len(s.prompt)} + response "
                f"{len(s.response)}) and the model's window is {window} B. Escape: a "
                f"shorter prompt/response, or a larger max_seq_len."
            )
        x = torch.tensor([list(ids)], dtype=torch.long, device=dev)
        logits, _none, step_counters = model(x, targets=None)
        counters.merge(step_counters)
        sums.append(response_logp(logits, x, len(s.prompt))[0])
        values.append(a.value)
        kept_groups.append(s.group)
        kept_weights.append(weights[i])
        counters.count("rl_samples")
    counters.count("rl_steps")
    if not sums:
        return torch.zeros((), device=dev, requires_grad=True), counters
    loss = pg_loss(torch.stack(sums), kept_weights, values, kept_groups)
    if not loss.requires_grad:
        loud(
            "rl_step built a loss with no grad_fn: the forward ran under "
            "torch.no_grad() (or every parameter has requires_grad=False), so a "
            "backward would train nothing. Escape: call rl_step outside the no_grad "
            "block."
        )
    return loss, counters
