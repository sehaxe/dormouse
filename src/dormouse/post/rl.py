def group_stats(verdicts: Sequence[Verdict], lengths: Sequence[int], cfg: RLConfig) -> GroupStats:
    """The group's pass rate and `ℓ*_q` — the percentile of the SUCCESSFUL lengths.

    A failure's length never enters the quantile (MiMo's Eq. 4 is explicit that
    `ℓ*_q` is the percentile over `P`, the passing set): the reference length is
    what a *correct* answer costs, so a group of long failures cannot raise it.
    """
    if len(verdicts) != len(lengths):
        loud(
            f"group_stats: {len(verdicts)} verdicts vs {len(lengths)} lengths. Escape: "
            f"one length per verdict."
        )
    if not verdicts:
        loud("group_stats: an empty group has no pass rate and no quantile.")
    for i, n in enumerate(lengths):
        if n < 0:
            loud(f"group_stats: lengths[{i}]={n}: a length cannot be negative.")
    passed = [n for v, n in zip(verdicts, lengths, strict=True) if v.passed]
    pass_rate = len(passed) / len(verdicts)
    quantile_len = (
        float(torch.quantile(torch.tensor(passed, dtype=torch.float64), cfg.quantile))
        if passed
        else 0.0
    )
    return GroupStats(
        n=len(verdicts),
        pass_rate=pass_rate,
        quantile_len=quantile_len,
        gate_open=pass_rate > cfg.gate and quantile_len > 0.0,
    )


def reward(
    verdict: Verdict,
    solution: str,
    cfg: RLConfig,
    *,
    length: int,
    stats: GroupStats | None = None,
    counters: Counters | None = None,
) -> RewardTerms:
    """One item's multiplicative reward minus the group-relative length term.

    `length` is the RESPONSE's byte cost (the prompt is not the model's own
    output and is not priced); `solution` is the task's hidden reference, which
    `S_sol` measures the response against. `stats` is required whenever
    `cfg.length_penalty > 0`: the term is a function of the group, so a per-item
    call cannot evaluate it, and a missing group is a LOUD error rather than a
    silently inactive term.
    """
    if length < 0:
        loud(f"reward: length={length}: a response length cannot be negative.")
    r_test = 1.0 if verdict.passed else 0.0
    if cfg.quality == "thrift":
        ref = len(solution.encode("utf-8"))
        # A response at or under the reference's own byte cost is full quality; an
        # empty response is no solution at all, whatever the reference cost.
        s_sol = 0.0 if length <= 0 else min(1.0, ref / length)
    else:
        s_sol = 1.0
    # The two deterministic behaviour flags a Verdict can show: a refusal by the
    # sandbox screen (network/process/native code — `verifiers.py:211`), and an
    # empty response. MiMo's token-level flags (Eq. 5) are the deferred half.
    s_beh = 0.0 if (length <= 0 or verdict.reason.startswith("refused:")) else 1.0

    penalty = 0.0
    active = False
    if cfg.length_penalty > 0.0:
        if stats is None:
            loud(
                f"reward: cfg.length_penalty={cfg.length_penalty} is group-relative "
                f"(ℓ*_q is the percentile of the group's successful lengths) and no "
                f"stats were given, so the term cannot be evaluated. Escape: "
                f"group_rewards(...), or stats=group_stats(verdicts, lengths, cfg)."
            )
        if not stats.gate_open:
            # Below the gate: inactive, and COUNTED — a dead term must not read as
            # a mechanism (the notes' §2b failure mode).
            if counters is not None:
                counters.count("rl_len_penalty_gated")
        elif verdict.passed:
            # Eq. 4: X · clip((ℓ/ℓ*_q − 1 − δ)/(s − δ), 0, 1)^γ, on passes only.
            x = (length / stats.quantile_len - 1.0 - cfg.delta) / (cfg.s - cfg.delta)
            frac = min(max(x, 0.0), 1.0)
            penalty = cfg.length_penalty * frac**cfg.gamma
            active = True
            if counters is not None:
                counters.count("rl_len_penalty_active")
        # A failing item gets no length term: its reward is already 0, and Eq. 4's
        # 1[i ∈ P] is exactly this.
    return RewardTerms(
        r_test=r_test,
        s_sol=s_sol,
        s_beh=s_beh,
        length_penalty=penalty,
        total=r_test * s_sol * s_beh - penalty,
        len_penalty_active=active,
    )


def group_rewards(
    verdicts: Sequence[Verdict],
    solutions: Sequence[str],
    lengths: Sequence[int],
    cfg: RLConfig,
    *,
    counters: Counters | None = None,
) -> list[RewardTerms]:
    """One prompt group's rewards: `group_stats` once, then [`reward`] per item."""
    if not (len(verdicts) == len(solutions) == len(lengths)):
        loud(
            f"group_rewards: {len(verdicts)} verdicts, {len(solutions)} solutions, "
            f"{len(lengths)} lengths. Escape: one of each per sample."
        )
    stats = group_stats(verdicts, lengths, cfg)
    return [
        reward(v, sol, cfg, length=n, stats=stats, counters=counters)
        for v, sol, n in zip(verdicts, solutions, lengths, strict=True)
    ]


