"""The rollout runner: a byte-budgeted generation + a verifier decision.

`docs/research/2026-10-15-agentic-post-training.md` §5 rung (b) is "the rollout
runner", and §10 step 1 says build it with the verifier, on `code`. This is the
FUNCTION that reports the triple — `(trace, n_bytes, verdict)` — not a trainer:
nothing here updates a weight, and the generation goes through the SAME decode
path the CLI uses (`dormouse.model.decode.decode_bytes`), so a rollout is a
program a reader can reproduce.

The byte budget is the `correct@budget(bytes)` contract from
`docs/architecture/post-training.md`'s "Reward shape for token thrift" node:
every byte the rollout touches — the prompt, the response, and each generation
stroke — is counted, and generation stops before the budget is exceeded.
"""

from __future__ import annotations

from dataclasses import dataclass

from ..instrument import Counters, LoudError, loud
from ..model.decode import DEFAULT_TEMP, decode_bytes
from .tasks import Task
from .verifiers import Verdict, verify

#: `decode_bytes` refuses `temp <= 0` ("0 means greedy, not this flag"), so a
#: greedy rollout pins the temperature near zero: the softmax collapses to the
#: argmax and `multinomial` returns it deterministically. Reusing the one decode
#: path is the point — a second sampling loop would be the thing that drifts.
GREEDY_TEMP = 1e-6

#: One stroke is the 2-char hex record of one generated byte; the budget counts
#: it on top of the raw response byte (that is what "prompt+response+strokes"
#: means here).
STROKE_BYTES = 2

#: COUNTED verifier failures at the rollout boundary. `verify` is total (R3-1),
#: so this key must stay at 0 in a healthy run; a non-zero reading is a verifier
#: bug that failed one sample instead of killing the batch — and the reader can
#: see it without a traceback (ADR-0019).
COUNTERS = Counters()

__all__ = ["COUNTERS", "GREEDY_TEMP", "STROKE_BYTES", "Rollout", "rollout"]


@dataclass(frozen=True)
class Rollout:
    """One budgeted attempt: the generation strokes, the bytes it cost, and the
    verifier's decision. `passed` is the only thing the advantage reads."""

    trace: list[str]
    n_bytes: int
    verdict: Verdict

    @property
    def passed(self) -> bool:
        return self.verdict.passed


def rollout(
    model,
    task: Task,
    budget: int,
    *,
    temp: float = DEFAULT_TEMP,
    greedy: bool = False,
    device=None,
    generator=None,
) -> Rollout:
    """Generate under `budget` bytes, verify, and report the triple."""
    if budget <= 0:
        loud(f"rollout budget={budget}: a rollout needs a positive byte budget")
    prompt = task.prompt.encode("utf-8")
    if len(prompt) > budget:
        loud(
            f"rollout: the prompt is {len(prompt)} B and the budget is {budget} B — "
            "the response would never fit; raise the budget or shorten the prompt"
        )
    effective_temp = GREEDY_TEMP if greedy else temp
    response = b""
    trace: list[str] = []
    while True:
        # Cost of one more byte: +1 for the response byte, +STROKE_BYTES for its
        # stroke record. Stop the moment the next one would exceed the budget.
        cost = len(prompt) + len(response) + STROKE_BYTES * (len(trace) + 1) + 1
        if cost > budget:
            break
        window = prompt + response
        new = decode_bytes(
            model, window, 1, temp=effective_temp, device=device, generator=generator
        )[-1:]
        response += new
        trace.append(f"{new[0]:02x}")
    verdict = _verify_response(task.as_dict(), response, budget)
    n_bytes = len(prompt) + len(response) + STROKE_BYTES * len(trace)
    return Rollout(trace=trace, n_bytes=n_bytes, verdict=verdict)


def _verify_response(task: dict, response: bytes, budget: int) -> Verdict:
    """The verifier boundary: one hostile answer (or one verifier bug) fails a
    sample, never the rollout batch. The counter is the evidence it happened."""
    try:
        return verify(task, response.decode("utf-8", "replace"))
    except LoudError:
        raise  # the do-not-run class and a bad task reference stay LOUD
    except Exception as exc:  # a boundary guard: the batch survives a verifier bug
        COUNTERS.count("rollout_verify_error")
        used = min(len(response) / budget, 1.0) if budget > 0 else 0.0
        return Verdict(
            False,
            f"verify raised {type(exc).__name__}: the sample is failed, not the batch",
            used,
        )
