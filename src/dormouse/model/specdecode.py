"""Speculative byte decode: the DSpark draft proposes `spec_k` bytes, ONE target
forward verifies them, and the accepted prefix is emitted.

`decode_bytes` re-forwards the whole window per generated byte — one target
forward per byte, `O(n)` forwards for a reply. Speculative decoding is the way
out: the draft head (`dspark.py`) proposes a short block from ONE position's
`(h, logits)`, a single forward over `ctx + block` gives the target's
distribution at every proposed position, and the block is emitted up to the
first disagreement. Cost when the draft is right: ~1 forward per `spec_k`
bytes, and the emitted stream is distributed exactly as plain decode's.

## What this module reuses (nothing here is a second implementation)

The target forward is `decode.window_forward(model, ids, hidden=True)` — the
same `model(ids)` call `decode_bytes` makes, over a longer sequence. The draft
recurrence is `DSparkHead.step` — the same Eq 6 step `terms()` runs in
training.

## The inference-time reduction, and why it is one

Training builds a window from the CONSUMED sequence: at anchor `p`, step `s`
reads `h[p+s]`, the frozen logits at `p+s`, and `W1[x[p+s]]` (`dspark.py`
`terms()`). At decode time only ONE position exists — the last byte — so the
draft's `h` and base logits are held FIXED at that position for all `spec_k`
steps, and only the Markov feature `W1[x_{k-1}]` advances (through the draft's
own previous proposal, which is what Eq 6's `x_{k-1}` is). That is a deviation
from the trained window, and the acceptance rate IS its price: it is the one
number this module exists to measure.

## The verification rule: standard speculative sampling, not greedy verify

`accept_or_residual` is Leviathan et al. 2022 / Chen et al. 2023's rule:
propose `x ~ q`, accept with probability `min(1, p(x)/q(x))`, and on rejection
sample from the residual `norm(max(0, p - q))`. That is EXACT at any
temperature — the emitted byte is distributed as the target's `p` — where
greedy verify ("take the target's argmax") is exact only as `temp -> 0`. The
port's decode samples at a temperature, so a rule that changed the
distribution would change what the model IS; the cheaper greedy rule would be
a silent temperature change. At `temp -> 0` the two coincide (p and q are
one-hot), which is why the equivalence gate runs at `temp=1e-6`.

## The sliding window, stated rather than hidden

`decode_bytes` feeds the last `max_seq_len` bytes, and so does the state
forward here. The VERIFY forward feeds `ctx[-max_seq_len:] + block`, so a
position deep in the block sees up to `spec_k` bytes more history than the
sliding window would; the first position of every block sees exactly the plain
window (a causal forward at that index cannot see the block). While
`len(ctx) + spec_k <= max_seq_len` there is no difference at all and the two
decoders are byte-identical at `temp -> 0`; past it the deviation is COUNTED
(`spec_over_window`), not silent — and the extra history is real bytes of the
same stream, so only a measurement can say whether it moves a byte.

## The one thing that must be true of the TARGET: prefix causality

Everything above assumes a causal forward: the logits at position `i` depend on
`x[0..=i]` and on nothing after it. That is what makes ONE forward over
`ctx + block` equivalent to `spec_k` forwards over growing prefixes. It is NOT
true of a Mixture-of-Experts with capacity dropping: which assignments survive
depends on the routing statistics of the WHOLE window, so a token's output can
change when later tokens are appended. Measured on the tiny model
(`tests/test_specdecode.py::test_a_capacity_limited_moe_is_not_prefix_causal`):
at `moe_capacity=1.0` appending four bytes moves the last position's logits by
0.91 and flips its argmax; at `moe_capacity=0.0` (dropless, what `configs/b1.toml`
ships) the same probe agrees to 8e-7, i.e. fp noise. So on a dropping MoE this
decoder still runs and still reports an acceptance rate, but its bytes are not
guaranteed to be `decode_bytes`' bytes — COUNTED once per call as
`spec_non_causal`, never silent.
"""

from __future__ import annotations

from typing import NamedTuple

import torch

from ..instrument import Counters, loud
from .decode import window_forward

#: Draft bytes per round — burn's `dspark_k` default (`dspark.DEFAULT_K`).
DEFAULT_SPEC_K = 4


class SpecStats(NamedTuple):
    """What one spec-decode call did: the acceptance rate and what it cost.

    `drafted` counts proposals the draft made, `accepted` the ones the target
    agreed with — the acceptance rate's numerator and denominator. A stop byte
    or the byte budget can end the loop with accepted proposals never emitted,
    so `accepted` can exceed `emitted`; `forwards` counts EVERY `window_forward`
    call (state forwards included) and `per_byte_forwards` divides it by the
    bytes actually emitted. `counters` carries the same two numbers under the
    names the log line reads (`spec_draft`/`spec_accept`).
    """

    drafted: int
    accepted: int
    forwards: int
    per_byte_forwards: float
    rounds: int
    emitted: int
    counters: Counters

    @property
    def acceptance_rate(self) -> float:
        """`accepted / drafted`, 0.0 when nothing was drafted (never NaN)."""
        return self.accepted / self.drafted if self.drafted else 0.0


def accept_or_residual(
    p: torch.Tensor, q: torch.Tensor, x: int, generator: torch.Generator | None = None
) -> int:
    """The speculative-sampling test, one position: `x ~ q` in, `~ p` out.

    Accept `x` with probability `min(1, p(x)/q(x))`; on rejection draw from the
    residual `norm(max(0, p - q))`. The two branches together emit exactly `p`
    (see the module docstring), which is the property the temp-1 gate pins.
    """
    ratio = float(p[x]) / float(q[x]) if float(q[x]) > 0.0 else 1.0
    if ratio >= 1.0 or float(torch.rand((), device=p.device, generator=generator)) < ratio:
        return x
    residual = (p - q).clamp_min(0.0)
    total = float(residual.sum())
    return int(torch.multinomial(residual / total if total > 0.0 else p, 1, generator=generator))


def draft_block(
    head,
    ctx: list[int],
    h_last: torch.Tensor,
    base_last: torch.Tensor,
    k: int,
    temp: float,
    generator: torch.Generator | None = None,
) -> tuple[list[int], list[torch.Tensor]]:
    """`k` proposals from ONE position: the head's Eq 6 recurrence on its own output.

    Returns `(ids, probs)`: the proposed bytes and the DRAFT distribution `q`
    each was drawn from — the verify step needs `q` for the acceptance ratio.
    `head.step` is the same Eq 6 step `terms()` runs; the difference is only in
    the inputs, and it is the reduction named in the module docstring: `h` and
    `base` stay at the last position while `W1[x_{k-1}]` advances through the
    draft's own proposal.
    """
    assert head is not None, "draft_block needs the DSpark head"
    state = torch.zeros(1, head.markov_rank, dtype=h_last.dtype, device=h_last.device)
    h = h_last.reshape(1, -1)
    base = base_last.reshape(1, -1)
    prev_id = int(ctx[-1])
    ids: list[int] = []
    probs: list[torch.Tensor] = []
    for _ in range(k):
        prev = head.w1(torch.tensor([prev_id], dtype=torch.long, device=h.device))
        state, logits = head.step(state, prev, h, base)
        q = torch.softmax(logits[0] / temp, dim=-1)
        prev_id = int(torch.multinomial(q, 1, generator=generator))
        ids.append(prev_id)
        probs.append(q)
    return ids, probs


def spec_decode_bytes(
    model,
    prompt_bytes: bytes,
    n_bytes: int,
    *,
    spec_k: int = DEFAULT_SPEC_K,
    temp: float = 1.0,
    device: torch.device | str | None = None,
    generator: torch.Generator | None = None,
    stop: frozenset[int] | None = frozenset(),
    counters: Counters | None = None,
) -> tuple[bytes, SpecStats]:
    """`prompt + up to n_bytes` bytes from the draft-then-verify loop.

    One round: draft `spec_k` bytes from the carried state (one target forward
    when there is no carry), verify them with ONE target forward over
    `ctx[-max_seq_len:] + block`, walk the block left to right and emit it up to
    the first rejection — the rejected position gets the residual draw and the
    rest of the block is discarded, because the verify forward's later logits
    were computed over bytes that were not emitted. A fully accepted, fully
    emitted block leaves the verify forward's last position as the next round's
    state, which is why a right draft costs ~1 forward per `spec_k` bytes
    instead of 2.

    The contract is `decode_bytes`': at most `n_bytes` new bytes, a generated
    stop byte is appended and generation ends there, and at `temp -> 0` (where
    both samplers are deterministic) the byte string is IDENTICAL — provided the
    target is prefix-causal (module docstring: a capacity-dropping MoE is not,
    and that is COUNTED as `spec_non_causal`). `stats` carries the acceptance
    rate and the forward count; `counters`, when given, receives
    `spec_draft`/`spec_accept` (`spec_over_window` too when the verify window
    outgrew `max_seq_len`).
    """
    if not prompt_bytes:
        loud("spec decode needs a non-empty prompt (the first window is the prompt)")
    if temp <= 0:
        loud(f"temp={temp}: use a positive temperature (0 means greedy, not this flag)")
    if spec_k < 1:
        loud(
            f"spec_k={spec_k}: the draft block is at least one byte. Escape: "
            f"spec_k >= 1 ({DEFAULT_SPEC_K} is the burn default), or decode_bytes "
            f"for plain sliding-window decode."
        )
    head = getattr(model, "dspark", None)
    if head is None:
        loud(
            "spec decode needs the DSpark draft head and this model has none: it is "
            "built only when dspark_weight > 0. Escape: decode a checkpoint trained "
            "with --set dspark_weight>0, or use decode_bytes (plain decode)."
        )
    stop = frozenset() if stop is None else frozenset(stop)
    dev = torch.device(device) if device is not None else torch.device("cpu")
    was_training = model.training
    model.eval()
    ctx = list(prompt_bytes)
    window = int(model.cfg.max_seq_len)
    out = Counters() if counters is None else counters
    # The one property this decoder needs of the target, checked at the config
    # (module docstring): capacity dropping makes a token's output depend on
    # the whole window, so a verify forward is no longer equivalent to K plain
    # forwards. COUNTED, because the decoder still runs and its acceptance rate
    # is still a real measurement of THIS target.
    if float(getattr(model.cfg, "moe_capacity", 0.0)) > 0.0:
        out.count("spec_non_causal")
    budget = int(n_bytes)
    drafted = accepted = forwards = rounds = over_window = 0
    #: `(h, logits)` at the last EMITTED position — a verified state a fully
    #: accepted round hands to the next draft (the state forward it saves).
    state: tuple[torch.Tensor, torch.Tensor] | None = None
    with torch.no_grad():
        while budget > 0:
            if state is None:
                ids = torch.tensor([ctx[-window:]], dtype=torch.long, device=dev)
                logits, hidden = window_forward(model, ids, hidden=True)
                forwards += 1
                assert hidden is not None, "hidden=True returned no hidden state"
                state = (hidden[-1].to(torch.float32), logits[-1])
            h_last, base_last = state
            proposals, qs = draft_block(head, ctx, h_last, base_last, spec_k, temp, generator)
            assert proposals, "a draft round must propose at least one byte"
            drafted += len(proposals)
            rounds += 1
            # The block's own bytes are always in view; only the context in
            # front of them can be pushed out, and that is the counted case.
            keep = window + len(proposals)
            ext = ctx + proposals
            if len(ext) > keep:
                over_window += 1
            vids = torch.tensor([ext[-keep:]], dtype=torch.long, device=dev)
            vlogits, vhidden = window_forward(model, vids, hidden=True)
            forwards += 1
            assert vhidden is not None, "hidden=True returned no hidden state"
            p = torch.softmax(vlogits / temp, dim=-1)
            first = vlogits.shape[0] - len(proposals)  # `p[first-1]` predicts proposals[0]
            new: list[int] = []
            rejected = False
            for j, prop in enumerate(proposals):
                got = accept_or_residual(p[first - 1 + j], qs[j], prop, generator)
                if got != prop:
                    rejected = True
                new.append(got)
                if rejected:
                    break
            accepted += len(new) - int(rejected)
            emitted_all = True
            for b in new:
                ctx.append(b)
                budget -= 1
                if b in stop:
                    budget = 0
                    emitted_all = False
                    break
                if budget == 0:
                    emitted_all = False
                    break
            # A carry is valid only when the WHOLE block was emitted: otherwise
            # the verify forward's last logits predict a byte that follows a
            # prefix that was not emitted.
            state = (
                None
                if rejected or not emitted_all
                else (vhidden[-1].to(torch.float32), vlogits[-1])
            )
    model.train(was_training)
    emitted = len(ctx) - len(prompt_bytes)
    out.count("spec_draft", drafted)
    out.count("spec_accept", accepted)
    out.count("spec_over_window", over_window)
    stats = SpecStats(
        drafted=drafted,
        accepted=accepted,
        forwards=forwards,
        per_byte_forwards=forwards / max(emitted, 1),
        rounds=rounds,
        emitted=emitted,
        counters=out,
    )
    return bytes(ctx), stats


