#!/usr/bin/env python3
"""The engine benchmark: bytes/s, ms/step, peak GiB and MFU on the real recipe.

    bash scripts/bench_engine.sh --quick          # 3 shapes x 50 steps
    bash scripts/bench_engine.sh --full           # 7 shapes x 200 steps
    bash scripts/bench_engine.sh --quick --dry-run  # commands + bills, CPU only

A shape is `batch x seq_len`. Every run is the trainer itself, launched with the
flags `scripts/recipe_ladder.sh` uses (defaults here are that recipe:
`flagship3_dense`, fwedu bytes, `opt=mix`, `muon_lr_mult=12`, `lr=3e-4`,
`mix_v7`, `doc_masking=false`, seed 1). Two deliberate departures, both named:

* `eval=false` — eval wall time enters the next telemetry window and would be
  read as a slower step; quality is the ladder's job, this file measures rate.
* `log_every=10`, and the steady state is the median of the LAST THREE log
  windows (the `tokens_per_s` the trainer itself writes); the spread across
  those three is printed, never a single lucky window.

THE LEDGER. `flops_per_byte` is `scripts/mod_ledger.ledger(cfg, capacity=
cfg.mod_capacity, seq_len=T).total` (training MFLOP/byte, x3 over the forward),
not a new formula. For the default `flagship3_dense` at s1024 it reproduces the
repo's measured `691.37 MFLOP/byte` (FlopCounterMode,
`docs/reviews/2026-11-06-control-transformer.md` §1). At s512 the T-term is
smaller, so the bill is shape-dependent — one reason a speed claim must name
its shape.

THREE MFU LEDGERS EXIST in this repo (attention-only / full `macs_per_token` /
MoE dense-down; they disagree by up to 3.9x —
`docs/research/2026-11-05-small-model-mfu.md` §0.2), and the DENOMINATOR is
also contested (§0.3: 45.7 measured on a 5060 Ti, 47.7 pinned by
`bench_compile.py` for this box, 88.7 the 5070 Ti's FP16/FP32-accum spec).
Every row records `ledger` and `peak_tflops`; a number without both is not a
number. `--peak-tflops` changes the denominator, never silently.

PEAK GiB is `torch.cuda.max_memory_allocated()` read by a generated wrapper
AFTER the real `dormouse.cli` entry point returns (`_bench_peak.py` in the run
directory — it adds no flags and does not touch the training path). It is not
`nvidia-smi` residency and not reserved memory.

`--quick` and `--full` REFUSE (exit 2) on a box with no free card: a benchmark
that silently measures nothing is the defect. `--dry-run` resolves every
command and bill on CPU and never consults the card.
"""

from __future__ import annotations

import argparse
import json
import math
import os
import re
import shutil
import statistics
import subprocess
import sys
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path

PORT = Path(__file__).resolve().parents[1]
REPO = PORT.parent
SRC = PORT / "src"
SCRIPTS = PORT / "scripts"
for _path in (str(SRC), str(SCRIPTS)):
    if _path not in sys.path:
        sys.path.insert(0, _path)

from _lane import data_missing, preflight  # noqa: E402

from dormouse.cli import _split_sets  # noqa: E402
from dormouse.config import ModelConfig, load_preset, load_run  # noqa: E402
from dormouse.instrument import LoudError  # noqa: E402

#: This box's pinned bf16 denominator (`scripts/bench_compile.py:PEAK_TFLOPS`;
#: `docs/research/2026-11-05-small-model-mfu.md` §0.3 says the true 5070 Ti
#: FP16/FP32-accum rate may be ~88.7 and 45.7 is a 5060 Ti measurement).
PEAK_TFLOPS = 47.7

#: Which bill `flops_per_byte` is. Recorded in every row: an MFU number must
#: name its ledger.
LEDGER = "mod_ledger.ledger(capacity=mod_capacity, seq_len=T).total x 3 (fwd+fwd+bwd)"

QUICK_STEPS = 50
FULL_STEPS = 200
#: Same 8 192 B/step as the live recipe: shape changes at constant step bytes.
QUICK_SHAPES = ((8, 1024), (4, 2048), (2, 4096))
#: Bytes/step 4K-16K, both axes: batch at s1024, sequence at b4/b2.
FULL_SHAPES = ((8, 512), (8, 1024), (8, 2048), (16, 1024), (4, 2048), (4, 4096), (2, 8192))

LOG_EVERY = 10
#: How many trailing telemetry windows define the steady state.
TAIL = 3

DEFAULT_CONFIG = str(PORT / "configs" / "flagship3_dense.toml")
DEFAULT_DATA = str(REPO / "data_local" / "best" / "fwedu_train.bin")
DEFAULT_EVAL = str(REPO / "data_local" / "best" / "fwedu_eval.bin")
DEFAULT_MIX = str(PORT / "configs" / "mix_v7.toml")

EXIT_BUSY = 2

#: Runs the REAL CLI entry point (`dormouse.cli.main`, so `LoudError` and exit
#: codes are the trainer's own), then reports the allocator's peak. Generated
#: into the run directory; the training flags are unchanged.
WRAPPER = '''\
"""Generated by bench_engine.py: the CLI plus one max_memory_allocated read."""

import sys


def main() -> int:
    import torch

    from dormouse.cli import main as cli

    try:
        cli()
    except SystemExit as exc:
        return int(exc.code or 0)
    finally:
        if torch.cuda.is_initialized():
            print(f"[bench] peak_gib={torch.cuda.max_memory_allocated() / 2**30:.3f}", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
'''

_PEAK_RE = re.compile(r"\[bench\] peak_gib=([0-9.]+)")


@dataclass(frozen=True)
class Shape:
    """One measured geometry."""

    batch: int
    seq_len: int

    @property
    def tag(self) -> str:
        return f"b{self.batch}s{self.seq_len}"

    @property
    def tokens_per_step(self) -> int:
        return self.batch * self.seq_len


# --- the arithmetic (pure, and what the CPU suite gates) --------------------


def ledger_for(cfg: ModelConfig, seq_len: int):
    """The repo's own training bill for this config at this window."""
    from mod_ledger import ledger

    capacity = cfg.mod_capacity if 0.0 < cfg.mod_capacity <= 1.0 else 1.0
    return ledger(cfg, capacity, seq_len=seq_len)


def flops_per_byte(cfg: ModelConfig, seq_len: int) -> float:
    """Training FLOPs per byte, from `mod_ledger.py` (FLOPs, not MFLOPs)."""
    return ledger_for(cfg, seq_len).total * 1e6


def step_tflops(flops_per_byte_: float, tokens_per_step: int, ms: float) -> float:
    """TFLOP/s implied by one step of `ms` milliseconds."""
    if not ms > 0:
        return float("nan")
    return flops_per_byte_ * tokens_per_step / (ms * 1e-3) / 1e12


def mfu(tflops: float, peak: float = PEAK_TFLOPS) -> float:
    """Fraction of the named denominator (`--peak-tflops`), never implicit."""
    return tflops / peak


def parse_shapes(text: str) -> tuple[Shape, ...]:
    """`"8x1024,4x2048"` -> shapes; anything else is a loud argument error."""
    shapes: list[Shape] = []
    for part in text.split(","):
        token = part.strip()
        match = re.fullmatch(r"(\d+)[xX](\d+)", token)
        if match is None:
            raise ValueError(f"shape {token!r} is not BATCHxSEQ (e.g. 8x1024)")
        batch, seq_len = int(match.group(1)), int(match.group(2))
        if batch < 1 or seq_len < 1:
            raise ValueError(f"shape {token!r}: batch and seq_len must be >= 1")
        shapes.append(Shape(batch, seq_len))
    if not shapes:
        raise ValueError("--shapes is empty")
    return tuple(shapes)


def summarize(events: list[dict], flops_per_byte_: float, peak: float) -> dict:
    """Steady state from the trainer's own telemetry rows.

    Bytes/s is the median `tokens_per_s` of the LAST `TAIL` log windows (one
    byte = one token in this byte-level lane); `spread_pct` is their
    (max - min) / median, the noise the single number must be read against.
    """
    run = next((e for e in events if e.get("event") == "run"), None)
    logs = [e for e in events if e.get("event") == "log" and e.get("tokens_per_s")]
    tail = logs[-TAIL:]
    rates = [float(e["tokens_per_s"]) for e in tail]
    nbytes = int(run["bytes_per_step"]) if run and run.get("bytes_per_step") else 0
    if not rates or not nbytes:
        return {
            "bytes_per_s": float("nan"),
            "ms_step": float("nan"),
            "spread_pct": float("nan"),
            "tflops": float("nan"),
            "mfu": float("nan"),
            "windows": len(rates),
        }
    rate = statistics.median(rates)
    ms = 1e3 * nbytes / rate
    spread = (max(rates) - min(rates)) / rate * 100.0
    tflops = step_tflops(flops_per_byte_, nbytes, ms)
    return {
        "bytes_per_s": rate,
        "ms_step": ms,
        "spread_pct": spread,
        "tflops": tflops,
        "mfu": mfu(tflops, peak),
        "windows": len(rates),
    }


def parse_peak(text: str) -> float | None:
    """The wrapper's `[bench] peak_gib=` line, or None when CUDA never started."""
    hits = _PEAK_RE.findall(text)
    return float(hits[-1]) if hits else None


def fmt_rate(value: float) -> str:
    return "—" if not math.isfinite(value) else f"{value:,.0f}"


def fmt_float(value: float, digits: int, unit: str = "") -> str:
    if not math.isfinite(value):
        return "—"
    return f"{value:,.{digits}f}{unit}"


# --- the plan (commands and bills, no GPU) ---------------------------------


def positive_float(text: str) -> float:
    """An argparse type for a denominator: zero is not a denominator."""
    value = float(text)
    if value <= 0:
        raise argparse.ArgumentTypeError(f"{text!r}: must be > 0")
    return value


def parser() -> argparse.ArgumentParser:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--quick", action="store_true", help="3 shapes x 50 steps")
    mode.add_argument("--full", action="store_true", help="7 shapes x 200 steps")
    ap.add_argument("--shapes", default="", help="override: BATCHxSEQ[,BATCHxSEQ...]")
    ap.add_argument("--config", default=DEFAULT_CONFIG, help="preset name or .toml path")
    ap.add_argument("--data", default=DEFAULT_DATA, help="training .bin")
    ap.add_argument("--eval", dest="eval_file", default=DEFAULT_EVAL, help="held-out .bin")
    ap.add_argument("--mix", default=DEFAULT_MIX, help="mixture plan .toml")
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--fast", action="store_true", help="recipe_ladder FAST=1 rung")
    ap.add_argument(
        "--set",
        dest="sets",
        action="append",
        default=[],
        metavar="KEY=VALUE",
        help="one extra --set, appended last (repeatable); model keys are priced",
    )
    ap.add_argument("--peak-tflops", type=positive_float, default=PEAK_TFLOPS)
    ap.add_argument("--out-dir", default=str(Path.home() / "logs" / "bench"))
    ap.add_argument("--tag", default="", help="suffix for this run's files")
    ap.add_argument("--dry-run", action="store_true", help="print the plan as JSON, CPU only")
    return ap


def shapes_for(args: argparse.Namespace) -> tuple[Shape, ...]:
    if args.shapes:
        return parse_shapes(args.shapes)
    return tuple(Shape(*pair) for pair in (QUICK_SHAPES if args.quick else FULL_SHAPES))


def build_argv(
    args: argparse.Namespace,
    shape: Shape,
    *,
    steps: int,
    model_overrides: dict[str, object],
    python: str,
    wrapper: Path,
    run_dir: Path,
    jsonl: Path,
) -> list[str]:
    """The exact trainer argv: recipe_ladder's flags plus this shape's geometry."""
    cmd = [
        python,
        "-u",
        str(wrapper),
        "train",
        args.config,
        "--data",
        args.data,
        "--eval",
        args.eval_file,
        "--set",
        f"steps={steps}",
        "--set",
        f"batch={shape.batch}",
        "--set",
        f"seq_len={shape.seq_len}",
        "--set",
        f"seed={args.seed}",
        "--set",
        "lr=3e-4",
        "--set",
        "opt=mix",
        "--set",
        "muon_lr_mult=12",
        "--set",
        f"mix_plan={args.mix}",
        "--set",
        "doc_masking=false",
        "--set",
        "eval=false",
        "--set",
        f"log_every={LOG_EVERY}",
        "--set",
        "ckpt_every=1000000",
        "--set",
        f"out_dir={run_dir}",
        "--json-log",
        str(jsonl),
    ]
    for key, value in model_overrides.items():
        cmd += ["--set", f"{key}={value}"]
    if args.fast:
        cmd += ["--set", "ns_dtype=bf16", "--set", "muon_state_dtype=bf16"]
    for one in args.sets:
        cmd += ["--set", one]
    return cmd


def plan(
    args: argparse.Namespace,
    *,
    python: str,
    wrapper: Path,
    out_dir: Path,
    stamp: str,
) -> tuple[int, list[dict]]:
    """Resolve every shape: model config, ledger bill, argv. No writes, no GPU."""
    steps = QUICK_STEPS if args.quick else FULL_STEPS
    model_sets, train_sets = _split_sets(args.sets)
    # `load_preset`, not `load_run`: the preset's default train seq (`small`)
    # can exceed a tiny model's window, and the shape's own train overrides are
    # what must be validated, not the unused preset default.
    base = load_preset(args.config)
    rows: list[dict] = []
    for shape in shapes_for(args):
        overrides: dict[str, object] = dict(model_sets)
        if shape.seq_len > base.max_seq_len:
            overrides["max_seq_len"] = shape.seq_len
        run = load_run(
            args.config,
            model_overrides=overrides,
            train_overrides={
                **train_sets,
                "steps": steps,
                "batch": shape.batch,
                "seq_len": shape.seq_len,
            },
        )
        led = ledger_for(run.model, shape.seq_len)
        tokens = shape.tokens_per_step * run.train.grad_accum
        jsonl = out_dir / f"{stamp}.{shape.tag}.jsonl"
        rows.append(
            {
                "tag": shape.tag,
                "batch": shape.batch,
                "seq_len": shape.seq_len,
                "steps": steps,
                "bytes_per_step": tokens,
                "grad_accum": run.train.grad_accum,
                "params": led.params,
                "flops_per_byte": led.total * 1e6,
                "tflops_per_step": led.total * 1e6 * tokens / 1e12,
                "model_overrides": overrides,
                "run_dir": str(out_dir / "runs" / f"{stamp}_{shape.tag}"),
                "jsonl": str(jsonl),
                "log": str(out_dir / f"{stamp}.{shape.tag}.log"),
                "cmd": build_argv(
                    args,
                    shape,
                    steps=steps,
                    model_overrides=overrides,
                    python=python,
                    wrapper=wrapper,
                    run_dir=out_dir / "runs" / f"{stamp}_{shape.tag}",
                    jsonl=jsonl,
                ),
            }
        )
    return steps, rows


# --- the run ---------------------------------------------------------------


def card_refusal() -> str | None:
    """`None` when a free card exists, else the loud reason to stop."""
    if shutil.which("nvidia-smi") is None:
        return "nvidia-smi is not on PATH: this box has no CUDA device"
    listing = subprocess.run(["nvidia-smi", "-L"], capture_output=True, text=True)
    if listing.returncode != 0 or not listing.stdout.strip():
        return "nvidia-smi sees no device: this box has no CUDA device"
    return preflight("cuda")


def data_refusal(args: argparse.Namespace) -> str | None:
    return data_missing(args.data, args.eval_file, args.mix)


def gpu_name() -> str:
    try:
        out = subprocess.run(
            ["nvidia-smi", "--query-gpu=name", "--format=csv,noheader"],
            capture_output=True,
            text=True,
            check=True,
        ).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return ""
    return out.splitlines()[0].strip() if out else ""


def git_revision() -> tuple[str, bool]:
    def _git(*argv: str) -> str:
        return subprocess.run(
            ["git", "-C", str(REPO), *argv],
            capture_output=True,
            text=True,
            check=True,
        ).stdout.strip()

    try:
        return _git("rev-parse", "--short", "HEAD"), bool(_git("status", "--porcelain"))
    except (OSError, subprocess.CalledProcessError):
        return "", False


def write_wrapper(out_dir: Path) -> Path:
    path = out_dir / "_bench_peak.py"
    path.write_text(WRAPPER, encoding="utf-8")
    return path


def child_env() -> dict[str, str]:
    """The recipe's environment: card 0, the checkout's src first on the path."""
    env = dict(os.environ)
    env["CUDA_VISIBLE_DEVICES"] = "0"
    env["PYTHONPATH"] = str(SRC)
    return env


def _error_line(text: str) -> str:
    for line in reversed(text.splitlines()):
        if "out of memory" in line.lower() or "loud:" in line or "error" in line.lower():
            return line.strip()[:300]
    return (text.strip().splitlines() or ["(no output)"])[-1][:300]


def run_one(row: dict, args: argparse.Namespace) -> dict:
    jsonl = Path(row["jsonl"])
    log = Path(row["log"])
    jsonl.unlink(missing_ok=True)
    log.parent.mkdir(parents=True, exist_ok=True)
    with log.open("w", encoding="utf-8") as sink:
        proc = subprocess.run(
            row["cmd"],
            cwd=PORT,
            stdout=sink,
            stderr=subprocess.STDOUT,
            env=child_env(),
        )
    text = log.read_text(encoding="utf-8", errors="replace")
    events: list[dict] = []
    if jsonl.is_file():
        for line in jsonl.read_text(encoding="utf-8").splitlines():
            try:
                events.append(json.loads(line))
            except json.JSONDecodeError:
                continue
    metrics = summarize(events, row["flops_per_byte"], args.peak_tflops)
    oom = "out of memory" in text.lower()
    if proc.returncode == 0 and metrics["windows"] > 0:
        status = "ok"
    elif oom:
        status = "oom"
    else:
        status = "error"
    out = {
        **row,
        "event": "shape",
        **metrics,
        "status": status,
        "returncode": proc.returncode,
        "peak_gib": parse_peak(text),
        "why": "" if status == "ok" else _error_line(text),
        "ledger": LEDGER,
        "peak_tflops": args.peak_tflops,
    }
    return out


def markdown(rows: list[dict], header: dict) -> str:
    lines = [
        f"# bench_engine {header['mode']} · {Path(header['config']).name}",
        "",
        f"`{header['git'] or 'unknown revision'}` · {header['gpu'] or 'unknown GPU'} · "
        f"{header['params']:,} params · {header['steps']} steps · seed {header['seed']} · "
        f"peak {header['peak_tflops']} TFLOP/s",
        "",
        f"ledger: {header['ledger']}",
        "",
        "| shape | steps | B/step | ms/step | B/s | peak GiB | MFLOP/B | TFLOP/s | "
        "MFU | ±3 win | status |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|",
    ]
    for r in rows:
        mflop = r["flops_per_byte"] / 1e6
        lines.append(
            f"| {r['batch']}×{r['seq_len']} | {r['steps']} | {r['bytes_per_step']:,} | "
            f"{fmt_float(r['ms_step'], 1)} | {fmt_rate(r['bytes_per_s'])} | "
            f"{fmt_float(r['peak_gib'] or float('nan'), 2)} | {fmt_float(mflop, 1)} | "
            f"{fmt_float(r['tflops'], 2)} | {fmt_float(r['mfu'] * 100, 1, '%')} | "
            f"±{fmt_float(r['spread_pct'], 1, '%')} | {r['status'].upper()} |"
        )
    lines += [
        "",
        "A speed claim names its shape and its ledger. See `docs/guides/benchmarking.md`.",
        "",
    ]
    return "\n".join(lines)


def dry_run(args: argparse.Namespace) -> int:
    out_dir = Path(args.out_dir).expanduser().resolve()
    steps, rows = plan(
        args,
        python=sys.executable,
        wrapper=out_dir / "_bench_peak.py",
        out_dir=out_dir,
        stamp=f"dryrun{args.tag}",
    )
    print(
        json.dumps(
            {
                "event": "dry_run",
                "mode": "quick" if args.quick else "full",
                "config": args.config,
                "steps": steps,
                "seed": args.seed,
                "peak_tflops": args.peak_tflops,
                "ledger": LEDGER,
                "shapes": rows,
            }
        )
    )
    return 0


def run(args: argparse.Namespace) -> int:
    why = card_refusal() or data_refusal(args)
    if why is not None:
        print(
            f"\n=== REFUSED: {why}\n"
            f"=== nothing was measured: a throughput number from a box that cannot run\n"
            f"=== the recipe is not a number. Re-run when the card is free.\n"
            f"=== exit {EXIT_BUSY}\n",
            flush=True,
        )
        return EXIT_BUSY

    out_dir = Path(args.out_dir).expanduser().resolve()
    out_dir.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now(UTC).strftime("%Y%m%dT%H%M%SZ") + args.tag
    wrapper = write_wrapper(out_dir)
    steps, rows = plan(args, python=sys.executable, wrapper=wrapper, out_dir=out_dir, stamp=stamp)
    revision, dirty = git_revision()
    header = {
        "event": "bench",
        "schema": 1,
        "mode": "quick" if args.quick else "full",
        "config": args.config,
        "steps": steps,
        "seed": args.seed,
        "peak_tflops": args.peak_tflops,
        "ledger": LEDGER,
        "gpu": gpu_name(),
        "git": revision + ("-dirty" if dirty else ""),
        "params": rows[0]["params"] if rows else 0,
        "created": datetime.now(UTC).isoformat(timespec="seconds"),
    }
    print(
        f"=== bench {header['mode']}: {len(rows)} shapes x {steps} steps · "
        f"{Path(args.config).name} · {header['params']:,} params · "
        f"peak {args.peak_tflops} TFLOP/s",
        flush=True,
    )
    jsonl_out = out_dir / f"{stamp}.jsonl"
    results: list[dict] = []
    with jsonl_out.open("w", encoding="utf-8") as sink:
        sink.write(json.dumps(header) + "\n")
        sink.flush()
        for row in rows:
            print(
                f"=== {row['tag']} · {row['bytes_per_step']:,} B/step · "
                f"{row['flops_per_byte'] / 1e6:.1f} MFLOP/B · {row['steps']} steps",
                flush=True,
            )
            result = run_one(row, args)
            results.append(result)
            sink.write(json.dumps(result) + "\n")
            sink.flush()
            print(
                f"    {result['status'].upper()}: "
                f"{fmt_float(result['ms_step'], 1)} ms/step · "
                f"{fmt_rate(result['bytes_per_s'])} B/s · "
                f"{fmt_float(result['peak_gib'] or float('nan'), 2)} GiB · "
                f"{fmt_float(result['mfu'] * 100, 1, '%')} MFU",
                flush=True,
            )
            if result["status"] == "error":
                print(f"    stopped: {result['why']}", flush=True)
                break
    table = markdown(results, header)
    md_out = out_dir / f"{stamp}.md"
    md_out.write_text(table, encoding="utf-8")
    print("\n" + table)
    print(f"jsonl: {jsonl_out}\ntable: {md_out}")
    ok = len(results) == len(rows) and all(r["status"] in ("ok", "oom") for r in results)
    return 0 if ok else 1


def main(argv: list[str] | None = None) -> int:
    args = parser().parse_args(argv)
    try:
        return dry_run(args) if args.dry_run else run(args)
    except LoudError as exc:
        # A bad `--set` or an unusable config is not a benchmark result.
        print(f"loud: {exc}", file=sys.stderr, flush=True)
        return 1


