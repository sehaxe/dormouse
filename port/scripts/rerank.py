"""The energy RERANKER: K rollouts per task, the lowest-energy one wins.

    uv run python scripts/rerank.py --out-dir checkpoints --ckpt-name <run> \
        --cls math --tasks 32 --k 8 --n-new 96 --seed 1

**This script is the measurement, not a claim.** It prints pass@1 (rollout 0),
pass@1 of the ENERGY-SELECTED rollout, and pass@K (any rollout passes), scored
by the repo's deterministic verifiers (`post/verifiers.py`). Until it runs, the
energy head has no quality number at all — the same rule the A/B
(`scripts/ab_energy.py`) carries.

**What is scored.** A rollout's energy is the MEAN over its generated bytes of
`e(h_t, embed[y_{t+1}])`, where `h_t` is the state the model's `lm_head` read
at byte `t` (one teacher-forced forward over the rollout, `window_forward(...,
hidden=True)`), and `e` is `EnergyHead.energy` (`model/energy.py`). Mean, not
sum: every rollout of one call has the same length, and a sum would let a
longer rollout lose on length alone. The candidate set is the model's own
`embed.weight` — all 256 bytes, enumerated in one matmul.

**Selection.** `pick` is `argmin` over the K energies; ties take the earliest
rollout, so a fixed `--seed` reproduces both the rollouts (one
`torch.Generator` per (task, k)) and the choice. The checkpoint must have been
trained with `energy_weight > 0` (`model.energy` is built IFF the weight is on);
a plain checkpoint is refused, not silently reranked by chance.

**What it does NOT do.** No MCMC, no gradient of the energy, no second model:
EBT's inference is energy minimisation, and with 256 candidates the minimum is
an argmin over the enumerated set. No training and no verdict.
"""

from __future__ import annotations

import argparse

import torch

from dormouse.instrument import loud
from dormouse.model.decode import decode_bytes, window_forward
from dormouse.post.tasks import build_tasks
from dormouse.post.verifiers import verify
from dormouse.serve import load_checkpoint


def rollout_generator(seed: int, task_index: int, k: int, device="cpu") -> torch.Generator:
    """The (task, rollout) generator — a pure function, so a run is replayable."""
    gen = torch.Generator(device=torch.device(device))
    return gen.manual_seed(seed * 1_000_003 + task_index * 1_003 + k)


def sequence_energy(
    head, h: torch.Tensor, candidates: torch.Tensor, next_ids: torch.Tensor
) -> torch.Tensor:
    """The mean energy of the byte actually consumed at each state.

    `h [t, d]` (the states), `candidates [V, d]` (the byte embeddings),
    `next_ids [t]` (the byte each state predicted). All V candidates are scored
    in one matmul, then the real bytes are gathered — the enumerable-vocabulary
    form of EBT's energy.
    """
    assert h.ndim == 2 and next_ids.ndim == 1, "a rollout is one [t, d] state row"
    assert h.shape[0] == next_ids.shape[0], "one energy per consumed byte"
    scores = head.scores(h, candidates)  # [t, V]
    picked = scores.gather(1, next_ids.reshape(-1, 1)).squeeze(1)
    return picked.mean()


def pick(energies: torch.Tensor) -> int:
    """The lowest-energy rollout; ties take the earliest (deterministic)."""
    assert energies.ndim == 1 and energies.numel() > 0, "need one energy per rollout"
    return int(torch.argmin(energies))


def score_rollout(model, head, prompt: bytes, response: bytes, device="cpu") -> float:
    """One teacher-forced forward over `prompt + response`, mean energy of the reply.

    The context is the model's own last `max_seq_len` bytes; if a prompt is long
    enough that early reply bytes fall outside it, the reply is scored on the
    bytes still inside the window (the same window the decoder itself sees).
    """
    assert response, "an empty reply has no byte to score"
    full = prompt + response
    ctx = full[:-1][-model.cfg.max_seq_len :]
    start = len(full) - 1 - len(ctx)
    ids = torch.tensor([list(ctx)], dtype=torch.long, device=device)
    _, h = window_forward(model, ids, hidden=True)
    # `h[j]` predicts `full[start + j + 1]`; drop the states that predict prompt.
    first = max(0, len(prompt) - 1 - start)
    h = h[first:]
    next_ids = torch.tensor(list(full[start + 1 + first :]), dtype=torch.long, device=device)
    assert next_ids.numel() == h.shape[0]
    cand = model.embed.weight.detach().to(torch.float32)
    return float(sequence_energy(head, h, cand, next_ids))


def rerank(args: argparse.Namespace) -> int:
    if args.k < 2:
        loud(f"--k={args.k}: a reranker needs at least two rollouts to choose between")
    if args.n_new < 1:
        loud(f"--n-new={args.n_new}: a rollout needs a positive byte budget")
    torch.manual_seed(args.seed)
    model, _run, dev = load_checkpoint(args.out_dir, args.ckpt_name, args.device)
    if model.energy is None:
        loud(
            f"{args.ckpt_name}: energy_weight is 0 in the checkpoint's snapshot, so no "
            f"head was built and there is nothing to rerank with. Escape: score a "
            f"checkpoint trained with energy_weight > 0, or rerun the A/B first."
        )
    model.eval()
    tasks = build_tasks(args.cls, args.seed, args.tasks)
    base = chosen = any_pass = 0
    with torch.no_grad():
        for i, task in enumerate(tasks):
            prompt = task.prompt.encode()
            replies: list[bytes] = []
            energies: list[float] = []
            for k in range(args.k):
                gen = rollout_generator(args.seed, i, k, device=dev)
                out = decode_bytes(
                    model, prompt, args.n_new, temp=args.temp, device=dev, generator=gen
                )
                reply = out[len(prompt) :]
                replies.append(reply)
                energies.append(score_rollout(model, model.energy, prompt, reply, device=dev))
            passed = [
                verify(task.as_dict(), reply.decode("utf-8", errors="replace")).passed
                for reply in replies
            ]
            best = pick(torch.tensor(energies))
            base += int(passed[0])
            chosen += int(passed[best])
            any_pass += int(any(passed))
    n = len(tasks)
    print(
        f"\nenergy reranker: {n} {args.cls} tasks, K={args.k}, temp={args.temp}, "
        f"n_new={args.n_new}, seed={args.seed}"
    )
    print(f"{'tasks':>6s} {'base@1':>7s} {'energy@1':>9s} {'pass@K':>7s} {'delta':>7s}")
    print(
        f"{n:6d} {base / n:7.3f} {chosen / n:9.3f} {any_pass / n:7.3f} {(chosen - base) / n:+7.3f}"
    )
    print(
        "base@1 = rollout 0; energy@1 = the lowest-energy rollout; pass@K = any. "
        "No quality claim until this runs on a checkpoint trained with "
        "energy_weight>0."
    )
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out-dir", default="checkpoints")
    ap.add_argument("--ckpt-name", required=True)
    ap.add_argument("--cls", default="math", choices=("math", "code"))
    ap.add_argument("--tasks", type=int, default=32)
    ap.add_argument("--k", type=int, default=8)
    ap.add_argument("--n-new", type=int, default=96)
    ap.add_argument("--temp", type=float, default=0.8)
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--device", default="auto")
    return rerank(ap.parse_args(argv))


if __name__ == "__main__":
    raise SystemExit(main())
