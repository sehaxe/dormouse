"""Byte-level decode for the port: sliding-window autoregressive next-byte.

The context is always the last `max_seq_len` bytes: every step re-forwards the
whole window, so the KDA state is rebuilt from exactly the bytes a reader of
the log would attribute to it — no incremental-kernel assumption hides inside
generation. Slow by design at large windows; correctness first, an incremental
decoder is a profile-then-build item.

`window_forward` is the ONE model call this module and `specdecode.py` share:
spec decode is this same forward over a longer sequence, never a second
implementation of it.

## `recurrent_decode` — the incremental decoder, built

`decode_bytes` is `O(window)` per byte (re-forward the window) and so `O(n²)`
over a reply; `recurrent_decode` is `O(1)` per byte and its context is unbounded.
It carries the **per-iteration KDA state** (the `[b, H, head_dim, head_dim]` fp32
recurrence state — one per loop-iteration slot, because the loop calls the
attention arm once per iteration, `loopblock._attn`) and NOT the residual stream:
`h` is a per-position quantity, so position `p`'s `T` iterations read `h` from
the SAME position (produced by the previous iteration of the same step) and the
state from iteration `i` at `p-1`. The token window survives only where a
non-attention arm needs bytes: the Engram's causal n-grams reach back
`max(engram.orders) - 1` = 3 bytes, so every step passes the last 4 bytes and
`LoopBlock._memory`'s padded-hidden trick keeps the first positions' outputs out
of the readout.

**Numerics: the same language, not the same bits** (the `kda.py` module
docstring's contract). The fused step (`fla.ops.kda.fused_recurrent_kda`) is the
exact per-token recurrence; the chunked pass (`chunk_kda`) it replaces is the
same recurrence with a different summation order, and the two sit **1.3e-2
(fp32) / 4.9e-2 (bf16) of the output RMS** apart at the port's test shape. The
generated bytes are therefore NOT guaranteed to be `decode_bytes`' bytes at the
same seed and temperature — the per-byte logits track, and the argmax usually
survives, but a near-tie can flip. That is a documented deviation, not a bug,
and the GPU gate (`tests/test_decode_recurrent.py`) is what keeps it bounded.

Two more deviations, both COUNTED rather than hidden:

* On a CPU box (no FLA) the step is the torch recurrence (`kda_step_torch`), not
  the SDPA fallback the training forward degrades to — SDPA has no `O(1)` state
  to carry (`_sdpa_path_carry` keeps a growing `(k, v)` context). So on CPU the
  recurrent decoder runs the model's TRUE attention arm where `decode_bytes`
  runs its COUNTED degradation.
* A capacity-dropping MoE (`moe_topk > 0` at `moe_capacity > 0`) is not
  prefix-causal: the drop set is a function of the window's composition, and a
  one-byte step sees a one-token window. The bytes still come out, counted
  `recurrent_non_causal` once per call — `specdecode.py`'s rule for the same
  defect. `moe_topk = 0` (what `small` ships) is per position and immune.
"""

from __future__ import annotations

import torch

from ..instrument import Counters, loud

#: The pseudo-count temperature keeps sampling near-greedy but never zerolock.
DEFAULT_TEMP = 0.8


def encode(text: str) -> bytes:
    """UTF-8 — the corpus is raw UTF-8 bytes, so a prompt is too."""
    return text.encode("utf-8")


def window_forward(
    model, ids: torch.Tensor, *, hidden: bool = False
) -> tuple[torch.Tensor, torch.Tensor | None]:
    """ONE `model(ids)` call: `(logits [t, vocab], hidden [t, d] | None)`.

    The one model call the port's decode paths share. `decode_bytes` takes the
    last row per byte; `specdecode` verifies a whole draft block with one call
    over a longer sequence — the same function, so a speculative verify cannot
    become a second implementation of the forward. Batch 1 by construction.

    `hidden` returns the tensor the DSpark draft head was TRAINED on
    (`model.py`: `hn = self.norm(out)`, the first argument of
    `dspark_aux_loss`), captured with a forward hook on `model.norm` because
    `forward` does not return it — an observation of the one call, not a
    re-implementation of it.
    """
    assert ids.ndim == 2 and ids.shape[0] == 1, f"decode is batch 1, got {tuple(ids.shape)}"
    t = ids.shape[1]
    if not hidden:
        return model(ids)[0].reshape(t, -1), None
    if not hasattr(model, "norm"):
        loud(
            "hidden=True needs the byte-lm path (`model.norm`): the byteflow shapes "
            "have no norm, and the DSpark head is refused with use_byteflow. "
            "Escape: decode with use_byteflow=false."
        )
    captured: dict[str, torch.Tensor] = {}
    handle = model.norm.register_forward_hook(lambda _m, _i, out: captured.__setitem__("h", out))
    try:
        logits = model(ids)[0].reshape(t, -1)
    finally:
        handle.remove()
    if "h" not in captured:
        loud(
            "the forward never reached `model.norm`: the draft head's hidden state is "
            "undefined on this path. Escape: spec decode needs the plain byte-lm "
            "forward (no use_byteflow)."
        )
    return logits, captured["h"].reshape(t, -1)


def decode_bytes(
    model,
    prompt: bytes,
    n_new: int,
    *,
    temp: float = DEFAULT_TEMP,
    device: torch.device | str | None = None,
    generator: torch.Generator | None = None,
    stop: frozenset[int] | None = None,
) -> bytes:
    """Return `prompt + n_new` sampled bytes, temperature-scaled logits.

    `stop` names bytes that END the reply (the SFT template's `0x03`): a
    generated stop byte is appended and generation returns early, so the
    caller never has to trim the model's padding habits out of a reply. The
    default (`None`) keeps the historical contract — exactly `n_new` bytes.
    """
    if not prompt:
        loud("decode needs a non-empty prompt (the first window is the prompt)")
    if temp <= 0:
        loud(f"temp={temp}: use a positive temperature (0 means greedy, not this flag)")
    dev = torch.device(device) if device is not None else torch.device("cpu")
    was_training = model.training
    model.eval()
    ctx = list(prompt)
    window = model.cfg.max_seq_len
    with torch.no_grad():
        for _ in range(n_new):
            ids = torch.tensor([ctx[-window:]], dtype=torch.long, device=dev)
            logits, _ = window_forward(model, ids)
            probs = torch.softmax(logits[-1] / temp, dim=-1)
            nxt = int(torch.multinomial(probs, 1, generator=generator))
            ctx.append(nxt)
            if stop is not None and nxt in stop:
                break
    model.train(was_training)
    return bytes(ctx)


def _recurrent_forward(
    model,
    ctx: list[int],
    states: list,
    dev: torch.device,
    drop: int,
    counters: Counters,
) -> tuple[torch.Tensor, list]:
    """ONE position (the last byte of `ctx`) through the loop block, state carried.

    `ids` is the engram's byte window: the last `drop+1` bytes, where
    `drop = min(max_order-1, position)` so the first positions of the stream
    read a shorter window — the same `s = max(0, e-order)` semantics
    `engram.raw_keys` has, and the same clamp `_forward_segmented` uses. The
    readout for the context positions is padding that `_memory` slices off.
    """
    d = min(drop, len(ctx) - 1)
    ids = torch.tensor([ctx[-(d + 1) :]], dtype=torch.long, device=dev)
    h0 = model.embed(ids[:, -1:])
    return model.loop.recurrent_step(h0, ids, states, drop=d, counters=counters)


def _step_logits(
    model,
    ctx: list[int],
    states: list,
    dev: torch.device,
    drop: int,
    counters: Counters,
) -> tuple[torch.Tensor, list]:
    """`_recurrent_forward` + the head: (the last position's logits row, the new state).

    The head is `model.py`'s own two lines (`norm` then `lm_head`, fp32 — the
    burn rule that fixes `bf16 logits NaN`), applied to the readout the loop
    block returned; `decode_bytes` reaches the same row through `model(ids)`.
    """
    out, states = _recurrent_forward(model, ctx, states, dev, drop, counters)
    logits = model.lm_head(model.norm(out.reshape(-1, model.cfg.d_model).to(torch.float32)))
    return logits[-1], states


def recurrent_decode(
    model,
    prompt: bytes,
    n_new: int,
    *,
    temp: float = DEFAULT_TEMP,
    device: torch.device | str | None = None,
    generator: torch.Generator | None = None,
    stop: frozenset[int] | None = None,
    counters: Counters | None = None,
) -> bytes:
    """`decode_bytes`' contract, `O(1)` per byte — the state-carry decoder.

    Returns `prompt + n_new` sampled bytes (or fewer if a `stop` byte ends the
    reply early), exactly as `decode_bytes`; `counters` is the only added
    argument, and it is how a caller reads which arm ran (`kda_step` = the fused
    decode kernel, `kda_step_torch` = the CPU recurrence, `recurrent_non_causal`
    = a capacity-dropping MoE). The module docstring has the state-carry
    mechanism, the numerics contract and the two COUNTED deviations.

    Cost: the prompt is PREFILLED one byte at a time (position-major — the same
    function the full-window forward computes, see `LoopBlock.recurrent_step`),
    so a call is `O(len(prompt) + n_new)` steps of `O(1)` each. There is no
    chunked prefill: on CPU there is no chunk kernel, and keeping the prefill on
    the same arm as the steps means the state never changes representation.
    """
    if not prompt:
        loud("decode needs a non-empty prompt (the first window is the prompt)")
    if temp <= 0:
        loud(f"temp={temp}: use a positive temperature (0 means greedy, not this flag)")
    loop = getattr(model, "loop", None)
    if loop is None or getattr(model, "bf", None) is not None:
        loud(
            "recurrent decode needs the byte-lm path (`model.loop`): the byteflow "
            "shapes run the loop over K patch latents, not over the byte window. "
            "Escape: use_byteflow=false, or plain decode."
        )
    if loop.msa is not None:
        loud(
            "recurrent decode with use_msa: the block-sparse arm selects its blocks "
            "INSIDE one window, and a one-byte step has no window to select in — that "
            "is a model change wearing an inference flag. Escape: use_msa=false."
        )
    counters = Counters() if counters is None else counters
    if loop.moe.topk > 0 and loop.moe.capacity > 0.0:
        counters.count("recurrent_non_causal")
    dev = torch.device(device) if device is not None else torch.device("cpu")
    was_training = model.training
    model.eval()
    ctx = list(prompt)
    target = len(prompt) + n_new
    drop = 0 if loop.engram is None else max(loop.engram.orders) - 1
    states: list = [None] * model.cfg.max_iter
    with torch.no_grad():
        logits = None
        for _ in range(len(ctx)):  # prefill: one step per prompt byte
            logits, states = _step_logits(model, ctx, states, dev, drop, counters)
        while True:
            probs = torch.softmax(logits / temp, dim=-1)
            nxt = int(torch.multinomial(probs, 1, generator=generator))
            ctx.append(nxt)
            if (stop is not None and nxt in stop) or len(ctx) >= target:
                break
            logits, states = _step_logits(model, ctx, states, dev, drop, counters)
    model.train(was_training)
    return bytes(ctx)
