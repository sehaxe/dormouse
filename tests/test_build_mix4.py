"""The builders' load-bearing checks: filters, the eval carve, determinism.

Run without pyarrow/torch — the web test exercises the byte path only:

    uv run --with pytest python -m pytest port/tests/test_build_mix4.py -q
"""

from __future__ import annotations

import importlib.util
from pathlib import Path

import pytest

SCRIPT = Path(__file__).resolve().parents[1] / "scripts" / "build_mix4.py"
spec = importlib.util.spec_from_file_location("build_mix4", SCRIPT)
mix = importlib.util.module_from_spec(spec)
assert spec.loader is not None
spec.loader.exec_module(mix)


def test_render_pair_is_the_sft_template() -> None:
    rec = mix.render_pair("hi", "there")
    assert rec == b"\x01hi\n\x02there\x03"
    with pytest.raises(AssertionError):
        mix.render_pair("a\x01b", "c")
    with pytest.raises(AssertionError):
        mix.render_pair("a", "b\x03c")


def test_strip_html_drops_style_and_script_bodies() -> None:
    raw = "<style>.x{color:red}</style><p>Hello &amp; bye</p><script>var x=1</script>"
    assert mix.strip_html(raw) == "Hello & bye"


def test_math_filter_keeps_equation_prose_and_drops_noise() -> None:
    good = b"# A proof\n\n" + (b"word " * 130) + b"\n$\\frac{1}{2}$\n"
    ok, reason = mix.filter_math_doc(good)
    assert ok, reason

    assert mix.filter_math_doc(b"short $x$") == (False, "too_short")
    prose = b"plain prose " * 200
    assert mix.filter_math_doc(prose) == (False, "no_equation")
    forum = b"$x$ " + b">> quote\n" * 4 + b"word " * 130
    assert mix.filter_math_doc(forum) == (False, "forum_quote")
    assert mix.split_math_docs(b"a\n---\nb") == [b"a", b"b"]


def _code(**over) -> dict:
    body = "def f():\n    return " + "x + " * 80 + "1\n"
    row = {"code": body, "path": "pkg/mod.py", "language": "Python"}
    row.update(over)
    return row


def test_code_filter_drops_vendored_minified_generated() -> None:
    ok, reason, lang = mix.filter_code(_code())
    assert ok, reason
    assert lang == "Python"

    assert mix.filter_code(_code(path="vendor/x/mod.py"))[1] == "vendored_minified_path"
    assert mix.filter_code(_code(path="pkg/app.min.js"))[1] == "vendored_minified_path"
    assert mix.filter_code(_code(code="x = 1; " * 40 + "\n"))[1] == "too_few_lines"
    assert mix.filter_code(_code(code="!" * 300 + "\n\n"))[1] == "alnum"
    generated = "# Generated by tool\n" + ("x = 1\n" * 50)
    assert mix.filter_code(_code(code=generated))[1] == "generated"
    assert mix.filter_code(_code(code="var x = 1; " * 400 + "\n\n"))[1] == "minified"
    assert mix.filter_code(_code(language="Ruby"))[1] == "language"


def test_web_eval_is_carved_first_and_never_trains(tmp_path: Path, monkeypatch) -> None:
    shards = tmp_path / "web_shards"
    shards.mkdir()
    for i in range(10):
        # `word ` is 80% alphanumeric; the unique header keeps the shard hashes distinct.
        (shards / f"web_{i:05d}.txt").write_bytes(f"#{i}\n".encode() + b"word " * 30_000)
    monkeypatch.setitem(mix.SHARD_DIRS, "web", shards)
    out = tmp_path / "out"

    d = mix.Domain("web", 900 << 10, out, eval_target=150 << 10)
    assert d.start()
    mix.build_shards(d)
    entry = d.finish()
    train = (out / "web.bin").read_bytes()
    ev = (out / "web_eval.bin").read_bytes()
    assert len(train) >= 900 << 10
    assert len(ev) >= 100 << 10
    assert ev not in train
    proof = entry["eval"]["exclusion"]
    assert proof["pass"] and proof["overlap"] == 0
    assert proof["eval_docs"] == 1 and proof["train_docs"] >= 6

    again = mix.Domain("web", 900 << 10, out, eval_target=150 << 10)
    assert not again.start()

    out2 = tmp_path / "out2"
    d2 = mix.Domain("web", 900 << 10, out2, eval_target=150 << 10)
    assert d2.start()
    mix.build_shards(d2)
    e2 = d2.finish()
    assert e2["train_sha256"] == entry["train_sha256"]
    assert e2["eval"]["sha256"] == entry["eval"]["sha256"]
