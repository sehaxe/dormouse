def _busy_card() -> str | None:
    """The busy-card preflight: `None` = the card is ours, else WHY NOT.

    `pgrep -f "dormouse trai[n]"` AND the A/B battery drivers (`ab_*.py`) AND
    the card's own memory — AGENTS §1.5's "one heavy thing at a time", as three
    checks rather than one. The brackets keep `pgrep` from matching this
    process' own command line. A bench's precondition is never an error.
    """
    try:
        training = subprocess.run(
            ["pgrep", "-af", "dormouse trai[n]"], capture_output=True, text=True, timeout=15
        ).stdout.strip()
        battery = subprocess.run(
            ["pgrep", "-af", r"ab_[a-z0-9_]*\.p[y]"], capture_output=True, text=True, timeout=15
        ).stdout.strip()
        used = subprocess.run(
            ["nvidia-smi", "--query-gpu=memory.used", "--format=csv,noheader"],
            capture_output=True,
            text=True,
            timeout=15,
        ).stdout.strip()
    except Exception as e:  # noqa: BLE001 - a precondition, not a run's failure
        return f"cannot check the card ({e})"
    if training:
        return f"a training run is live: {training.splitlines()[0]}"
    if battery:
        return f"an A/B battery driver is live: {battery.splitlines()[0]}"
    mib = int(used.split()[0]) if used else -1
    if mib >= 1024:
        return f"the card already holds {mib} MiB"
    return None


