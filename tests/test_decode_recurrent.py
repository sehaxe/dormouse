"""State-carry (recurrent) decode — `O(1)` per byte instead of `O(window)`.

`decode_bytes` re-forwards the whole window per generated byte (`O(n²)` over a
reply); `recurrent_decode` (`model/decode.py`) carries the **per-iteration KDA
state** and steps one byte at a time (`model/kda.py::KDAAttention.step_state`).

Every gate here but the last is CPU and tiny — what has to be true is the
SEMANTICS (what is carried, what the readout equals, what the flags refuse), and
none of it needs a card. The FUSED step
(`fla.ops.kda.fused_recurrent_kda`) is CUDA-only, so the gate that runs it is
last and is skipped on a busy card; the CPU step is the exact torch recurrence
(`kda._recurrent_step`), which is also the fused kernel's anchor.

**The numerics contract is `kda.py`'s**: the step and the chunked pass are the
same recurrence with different summation orders (1.3e-2 fp32 / 4.9e-2 bf16 of
the output RMS at the port's test shape), so the recurrent decoder's BYTES are
never asserted equal to `decode_bytes`' on the CPU arm — where the two decoders
run two different attention arms by construction (the step is the true
recurrence, `decode_bytes` is the COUNTED SDPA fallback). The logits are what
the gates bound, and the CUDA gate is where the two arms meet.
"""

