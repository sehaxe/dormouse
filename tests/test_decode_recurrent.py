def _drop(model) -> int:
    """The left context the Engram's causal n-grams reach — `max(orders) - 1`."""
    return 0 if model.loop.engram is None else max(model.loop.engram.orders) - 1


def _prefill(model, prompt: list[int], dev: torch.device) -> tuple[torch.Tensor, list]:
    """The last prompt position's logits + the per-iteration state, one byte at a time.

    Exactly what `recurrent_decode` does before it samples — inlined so a test can
    read the logits the public function only samples from.
    """
    states: list = [None] * model.cfg.max_iter
    logits = None
    for i in range(len(prompt)):
        logits, states = _step_logits(model, prompt[: i + 1], states, dev, _drop(model), Counters())
    return logits, states


# ---------------------------------------------------- (a) the step IS the recurrence


def test_the_step_is_the_recurrence():
    """`_recurrent_step` × T == the per-token recurrence reference, fp32.

    The reference is `tests/test_kda_gpu.py::_recurrent` — the same transcription
    the fused kernel is anchored on — so this is the CPU half of that gate: the
    decode step IS KDA Eq 1, not a different recurrence wearing its name. The
    step normalizes q/k in-kernel-style (`+1e-6`), the reference is handed
    `F.normalize`d q/k, so the two differ by that eps (≤5e-7 relative) — the
    bound is a WIRING gate (a transposed head axis is O(1) off), not a
    certificate.
    """
    torch.manual_seed(0)
    cfg = tiny_cfg()
    attn = KDAAttention(cfg, device="cpu").eval()
    t = 32
    x = torch.randn(1, t, cfg.d_model)
    with torch.no_grad():
        q, k, v, g, beta = attn.projections(x)
        qn, kn = F.normalize(q.float(), dim=-1), F.normalize(k.float(), dim=-1)
        ref = _recurrent(qn, kn, v, g, beta, attn.scale)
        state = None
        steps = []
        for i in range(t):
            o, state = _recurrent_step(
                qn[:, i : i + 1],
                kn[:, i : i + 1],
                v[:, i : i + 1],
                g[:, i : i + 1],
                beta[:, i : i + 1],
                state,
                attn.scale,
            )
            steps.append(o)
        got = torch.cat(steps, dim=1)
    assert state is not None and state.dtype == torch.float32
    assert state.shape == (1, cfg.n_heads, cfg.head_dim, cfg.head_dim), tuple(state.shape)
    d = float((got - ref).abs().max()) / float(ref.abs().mean())
    print(f"[recurrent step] max/refmean={d:.3e}")
    assert d <= 1e-5, f"the step drifted from the recurrence: {d}"


def test_step_state_returns_the_state_the_chunked_arm_returns():
    """`step_state`'s contract: `[b, H, head_dim, head_dim]` fp32, and READ, not ignored.

    The shape/dtype is what `chunk_kda`'s `final_state` has (`kda.forward_state`),
    which is why the prefill and the steps can share one representation. The
    last assertion is the load-bearing one: a carried step must differ from a
    fresh one, or the state is decoration.
    """
    torch.manual_seed(0)
    cfg = tiny_cfg()
    attn = KDAAttention(cfg, device="cpu").eval()
    x = torch.randn(1, 4, cfg.d_model)
    c = Counters()
    with torch.no_grad():
        out, st = attn.step_state(x[:, :1], None, counters=c)
        out_b, st_b = attn.step_state(x[:, :1], None, counters=c)
        carried, _ = attn.step_state(x[:, 1:2], st, counters=c)
        fresh, _ = attn.step_state(x[:, 1:2], None, counters=c)
    assert out.shape == (1, 1, cfg.d_model)
    assert st.dtype == torch.float32 and st.shape == (1, cfg.n_heads, cfg.head_dim, cfg.head_dim)
    assert torch.equal(st, st_b), "state=None is position 0: two fresh steps are one function"
    assert not torch.allclose(carried, fresh), "the carried state must move the output"
    assert c["kda_step_torch"] == 4, c.line()


def test_the_torch_step_names_the_real_reason(monkeypatch):
    """`counters.why` is the ARM's reason, not the FLA warmup's stale "ok".

    With FLA healthy and grad enabled, the torch recurrence runs because the
    fused decode kernel ships no backward — the old code copied `fla_status`'s
    "warmup ok" into `why`, which reads as if the fused arm ran.
    """
    from dormouse.model import kda as kda_mod

    monkeypatch.setattr(kda_mod, "fla_status", lambda dev: (True, "warmup ok"))
    torch.manual_seed(0)
    attn = KDAAttention(tiny_cfg(), device="cpu").eval()
    x = torch.randn(1, 1, attn.n_heads * attn.head_dim, requires_grad=True)
    c = Counters()
    _out, st = attn.step_state(x, None, counters=c)
    print(f"[step reason] {c.line()} why={c.why}")
    assert c["kda_step_torch"] == 1, c.line()
    assert "grad enabled" in c.why and "warmup ok" not in c.why, c.why
    assert st.dtype == torch.float32


def test_a_state_without_carry_is_refused_in_both_paths():
    """A non-None `state` with `carry=False` would be SILENTLY dropped; refuse."""
    torch.manual_seed(0)
    attn = KDAAttention(tiny_cfg(), device="cpu").eval()
    x = torch.randn(1, 2, attn.n_heads * attn.head_dim)
    state = torch.zeros(1, attn.n_heads, attn.head_dim, attn.head_dim)
    with pytest.raises(LoudError, match="carry"):
        attn.forward_state(x, state, carry=False)
    # The fused path's own guard, before its `import fla` — so this is a CPU gate.
    with pytest.raises(LoudError, match="carry"):
        attn._fla_path(x, state, carry=False)


# -------------------------------------------- (b) the one-byte body IS the window body


def test_a_recurrent_prefill_is_the_window_forward_without_attention(byte_tensor):
    """No attention arm → the body is per position, so the steps reproduce the window.

    With `use_kda = false` nothing in the body mixes positions (the Engram's gate
    math is per position, `moe_topk = 0` is the dense per-position blend), so the
    one-byte steps must reproduce the full-window forward's LAST position. This
    pins the ORCHESTRATION — embed, controller, the Engram's byte window and its
    `drop` clamp, the readout, `norm` + `lm_head` — against `window_forward`.
    The attention arm is the next gate's business.
    """
    torch.manual_seed(0)
    model = tiny_model(use_kda=False, moe_topk=0)
    ids, _ = byte_tensor()
    ids = ids[:1, :16]
    prompt = [int(b) for b in ids[0]]
    with torch.no_grad():
        ref = window_forward(model, ids)[0][-1]
        got, states = _prefill(model, prompt, torch.device("cpu"))
    assert states == [], "use_kda=false has no attention state to carry"
    d = float((got - ref).abs().max())
    print(f"[recurrent prefill] max|dlogits|={d:.3e}")
    assert d <= 1e-5, f"the one-byte steps do not reproduce the window forward: {d}"


def test_the_position_major_order_is_the_iteration_major_order(monkeypatch, byte_tensor):
    """The step order cannot drift from the window's — with the SAME recurrence.

    On CPU the real window forward runs the COUNTED SDPA fallback, which is a
    different model, so the comparison arm is the exact torch recurrence handed
    to `forward_state` (the fused arm's own job on a card). With one recurrence
    on both sides the recurrent decode's last-position logits must equal the
    full-window forward's: that is the claim that iteration `i` at position `p`
    reads `h` from iteration `i-1` at the SAME position and the state from
    iteration `i` at `p-1` — and this is the only gate that can catch a
    MIS-INDEXED state slot (the no-attention gate has no states at all, the carry
    gate only checks that some state matters).
    """
    torch.manual_seed(0)
    model = tiny_model(moe_topk=0)
    ids, _ = byte_tensor()
    ids = ids[:1, :16]
    prompt = [int(b) for b in ids[0]]

    def torch_window_state(attn, x, state=None, counters=None, *, carry=False):
        """`forward_state`, but on the exact recurrence — the CPU comparison arm."""
        q, k, v, g, beta = attn.projections(x)
        outs, s = [], state
        for i in range(x.shape[1]):
            o, s = _recurrent_step(
                q[:, i : i + 1],
                k[:, i : i + 1],
                v[:, i : i + 1],
                g[:, i : i + 1],
                beta[:, i : i + 1],
                s,
                attn.scale,
            )
            outs.append(o)
        out = torch.cat(outs, dim=1).reshape(x.shape[0], x.shape[1], -1)
        return out, (s if carry else None)

    monkeypatch.setattr(KDAAttention, "forward_state", torch_window_state)
    with torch.no_grad():
        ref = window_forward(model, ids)[0][-1]
        got, _ = _prefill(model, prompt, torch.device("cpu"))
    d = float((got - ref).abs().max())
    print(f"[recurrent order] max|dlogits|={d:.3e}")
    assert d <= 1e-4, f"the step order drifted from the window order: {d}"


def test_the_carried_state_is_the_only_channel_from_an_early_byte():
    """Position 0 reaches position N's logits ONLY through the KDA state.

    `h` is not carried across bytes (`LoopBlock.recurrent_step`), so an early
    byte's only route to the last position is the per-iteration state. Two
    prompts differing at byte 0 must therefore move the last-position logits, and
    throwing the state away before the last step must move them too — the
    difference between a carried decode and `T` independent one-byte forwards.
    """
    torch.manual_seed(0)
    model = tiny_model(moe_topk=0)
    prompt = [3, 5, 7, 11, 13, 17, 19, 23]
    dev = torch.device("cpu")
    with torch.no_grad():
        base, _ = _prefill(model, prompt, dev)
        other, _ = _prefill(model, [4, *prompt[1:]], dev)
        dropped, _ = _step_logits(
            model, prompt, [None] * model.cfg.max_iter, dev, _drop(model), Counters()
        )
    moved = float((base - other).abs().max())
    lost = float((base - dropped).abs().max())
    print(f"[recurrent carry] early-byte move={moved:.3e} state-dropped move={lost:.3e}")
    assert moved > 1e-4, "an early byte must reach the last position through the state"
    assert lost > 1e-4, "the state is not load-bearing if dropping it changes nothing"


