# ------------------------------------------------------------------ (d) the O(1) claim


def test_per_byte_cost_does_not_grow_with_context():
    """`O(1)` per byte: the MARGINAL cost of a byte is flat in the context length.

    Measured on CPU with the torch step (the fused kernel is CUDA-only). The
    marginal cost is `T(L, 2n) - T(L, n)` with the SAME generator seed, so the
    two calls differ by exactly the last `n` steps — and the prefill, which is
    `O(L)`, cancels in the difference. A decoder that re-forwarded a window (or
    a step that read the whole context) would grow with L; the bound is 2x over
    a 32x span of context lengths, on the min of 3 runs (`process_time`, so the
    box's other tenants cannot inflate it).
    """
    model = tiny_model(moe_topk=0)
    n = 64
    lengths = (8, 64, 256)

    def marginal(length: int) -> float:
        prompt = bytes((i * 7 + 3) % 251 + 1 for i in range(length))
        best = float("inf")
        for _ in range(3):
            t0 = time.process_time()
            recurrent_decode(
                model, prompt, 2 * n, temp=0.8, generator=torch.Generator().manual_seed(1)
            )
            t1 = time.process_time()
            recurrent_decode(model, prompt, n, temp=0.8, generator=torch.Generator().manual_seed(1))
            t2 = time.process_time()
            best = min(best, (t1 - t0) - (t2 - t1))
        return best / n

    got = {length: marginal(length) for length in lengths}
    print("[recurrent O(1)] per-byte " + " ".join(f"L={k}:{v * 1e3:.3f}ms" for k, v in got.items()))
    lo, hi = min(got.values()), max(got.values())
    assert lo > 0.0, f"the marginal cost measured nothing: {got}"
    assert hi / lo < 2.0, f"the per-byte cost grows with context: {got}"


