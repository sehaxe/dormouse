@_cuda_step
def test_the_fused_step_tracks_the_chunked_decode():
    """The card's gate: the fused step and the chunked pass decode the same stream.

    Two claims, both on ONE model (built here, on the card, rather than loaded
    from `checkpoints/`: every snapshot in that directory predates the six-stub
    deletion and `_snapshot_run` now refuses it — a pre-existing condition, not
    this gate's):

    1. **the per-byte logits track.** The recurrent path's last-position logits
       (one fused step per prompt byte) against `window_forward`'s, bounded by
       the documented divergence class (`kda.py`: 1.3e-2 fp32 / 4.9e-2 bf16 of
       the KDA output RMS; the bound below is the looser bf16 class, `5e-2`
       relative to the logit max).
    2. **the greedy argmax survives it.** `temp -> 0` on both decoders for N
       bytes must give the SAME bytes — the task's own gate. The generated TEXT
       is allowed to differ at a real temperature (the two arms are the same
       language, not the same bits), but a wiring error (a transposed state
       axis, a swapped state slot) flips the argmax immediately. If this goes
       red, the model's top-1 gap is below the documented divergence: report it,
       do not loosen the bound silently.
    """
    from dormouse.model.kda import fla_status

    ok, why = fla_status("cuda", recheck=True)
    assert ok, f"the fused arm must be live on THIS card, not skipped: {why}"
    torch.manual_seed(0)
    cfg = tiny_cfg(bf16=False, moe_topk=0)
    model = DormouseModel(cfg, device="cuda").eval()
    prompt = b"The quick brown fox jumps over the lazy dog. "
    n = 8
    dev = torch.device("cuda")
    with torch.no_grad():
        chunked = decode_bytes(
            model,
            prompt,
            n,
            temp=1e-6,
            device=dev,
            generator=torch.Generator(device=dev).manual_seed(0),
        )
        c = Counters()
        rec = recurrent_decode(
            model,
            prompt,
            n,
            temp=1e-6,
            device=dev,
            generator=torch.Generator(device=dev).manual_seed(0),
            counters=c,
        )
        ids = torch.tensor([list(prompt)], dtype=torch.long, device=dev)
        ref = window_forward(model, ids)[0][-1]
        got, _ = _prefill(model, list(prompt), dev)
    assert c["kda_step"] == (len(prompt) + n - 1) * cfg.max_iter, c.line()
    assert "kda_step_torch" not in c, f"the fused step kernel must run on this card: {c.line()}"
    rel = float((got - ref).abs().max()) / float(ref.abs().max())
    print(
        f"[recurrent cuda] greedy bytes equal={chunked == rec} logits max/refmax={rel:.3e} "
        f"{c.line()}"
    )
    assert rel <= 5e-2, f"the step path's logits drifted from the window forward: {rel}"
    assert chunked == rec, "the greedy argmax did not survive the documented divergence"


@_cuda_step
def test_the_chunked_prefill_is_the_byte_prefill():
    """The card's gate: ONE `chunk_kda` prefill == the byte steps, within contract.

    The chunked prefill and the byte prefill are the same recurrence with
    different summation orders (the module docstring's class: 1.3e-2 fp32 /
    4.9e-2 bf16 of the output RMS at the port's shape). Bounded here: (1) the
    last-position logits and the carried state stay inside that class, (2) at
    `temp -> 0` both prefills decode the same bytes — a wiring error (a state
    that is not the one `step_state` consumes) flips the argmax immediately. If
    this goes red, report the measured gap; do not loosen the bound silently.
    """
    from dormouse.model.kda import fla_status

    ok, why = fla_status("cuda", recheck=True)
    assert ok, f"the chunked kernel must be live on THIS card: {why}"
    torch.manual_seed(0)
    cfg = tiny_cfg(bf16=False, moe_topk=0)
    model = DormouseModel(cfg, device="cuda").eval()
    prompt = b"The quick brown fox jumps over the lazy dog. "
    dev = torch.device("cuda")
    with torch.no_grad():
        ref_logits, ref_states = _prefill(model, list(prompt), dev)
        c = Counters()
        got_logits, got_states = _chunked_prefill(model, list(prompt), dev, c)
        chunked = recurrent_decode(
            model,
            prompt,
            8,
            temp=1e-6,
            device=dev,
            generator=torch.Generator(device=dev).manual_seed(0),
            prefill="chunked",
        )
        byte = recurrent_decode(
            model,
            prompt,
            8,
            temp=1e-6,
            device=dev,
            generator=torch.Generator(device=dev).manual_seed(0),
            prefill="byte",
        )
    assert c["prefill_chunked"] == 1, c.line()
    rel = float((got_logits - ref_logits).abs().max()) / float(ref_logits.abs().max())
    dmax = max(
        float((a - b).abs().max()) / (float(b.abs().max()) + 1e-30)
        for a, b in zip(got_states, ref_states, strict=True)
    )
    print(
        f"[chunked prefill cuda] logits max/refmax={rel:.3e} state={dmax:.3e} "
        f"greedy bytes equal={chunked == byte} {c.line()}"
    )
    assert rel <= 5e-2, f"the chunked prefill's logits drifted: {rel}"
    assert dmax <= 5e-2, f"the chunked prefill's state drifted: {dmax}"
    assert chunked == byte, "the greedy argmax did not survive the prefill divergence"
