def test_recurrent_decode_is_decode_bytes_contract():
    """Same call, same contract: `prompt + n`, a stop byte ends early, deterministic."""
    model = tiny_model(moe_topk=0)
    prompt = b"\x01 hi \n\x02 "
    gen = lambda: torch.Generator().manual_seed(0)  # noqa: E731 - a seed, not a function
    out = recurrent_decode(model, prompt, 12, temp=0.8, generator=gen())
    assert len(out) == len(prompt) + 12 and out.startswith(prompt)
    assert recurrent_decode(model, prompt, 12, temp=0.8, generator=gen()) == out
    # `range(256)` contains every byte, so the FIRST sampled byte ends the reply
    stopped = recurrent_decode(
        model, prompt, 12, temp=0.8, generator=gen(), stop=frozenset(range(256))
    )
    assert len(stopped) == len(prompt) + 1
    with pytest.raises(LoudError):
        recurrent_decode(model, b"", 4)
    with pytest.raises(LoudError):
        recurrent_decode(model, prompt, 4, temp=0.0)


